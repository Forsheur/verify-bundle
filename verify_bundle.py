def _x509_backend():
    """The one place this verifier asks for something outside the stdlib.

    Walking an X.509 chain means parsing certificates and checking ECDSA P-384
    and RSA-4096 signatures. That is a lot of cryptography to hand-roll for a
    check that DEGRADES cleanly: without it the media verdict above is exactly
    as strong, and only the manufacturer link goes unproven. `cryptography` is
    already an optional dependency here (decryption uses it), so this asks for
    nothing new to install.

    Returns None rather than raising: a missing package is a note, never a
    FAIL. A bundle does not become suspect because a reader lacks a wheel.
    """
    try:
        from cryptography import x509
        from cryptography.hazmat.primitives.asymmetric import ec, padding, rsa
        from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat
        return {"x509": x509, "ec": ec, "rsa": rsa, "padding": padding,
                "Encoding": Encoding, "PublicFormat": PublicFormat}
    except ImportError:
        return None


# --- minimal DER reader (stdlib) -------------------------------------------
#
# Only used for Android's KeyDescription extension, which no library parses for
# us: `cryptography` hands the extension over as opaque bytes, and Google's own
# parser is Java. It is a small, strictly-read-only walk — it never builds DER,
# so a bug here can refuse a good chain, never accept a bad one.

def _der_tlv(buf, off):
    """Read one TLV. Returns (cls, constructed, tag, content, next_off)."""
    b0 = buf[off]
    cls = b0 >> 6
    constructed = bool(b0 & 0x20)
    tag = b0 & 0x1F
    off += 1
    if tag == 0x1F:
        tag = 0
        while True:
            b = buf[off]
            off += 1
            tag = (tag << 7) | (b & 0x7F)
            if not b & 0x80:
                break
    ln = buf[off]
    off += 1
    if ln & 0x80:
        n = ln & 0x7F
        ln = int.from_bytes(buf[off:off + n], "big")
        off += n
    if off + ln > len(buf):
        raise ValueError("DER length runs past the end of the buffer")
    return cls, constructed, tag, buf[off:off + ln], off + ln


def _der_children(content):
    out, off = [], 0
    while off < len(content):
        cls, cons, tag, val, off = _der_tlv(content, off)
        out.append((cls, cons, tag, val))
    return out


def _der_int(raw):
    return int.from_bytes(raw, "big", signed=True) if raw else 0


def parse_key_description(ext_bytes):
    """Read Android's KeyDescription. Mirrors `attest/android.rs` field for field.

    Positional, exactly as the schema declares it — measuring lengths instead of
    reading positions is how a parser starts agreeing with the wrong layout.
    """
    _, _, _, top, _ = _der_tlv(ext_bytes, 0)
    seq = _der_children(top)
    if len(seq) < 8:
        raise ValueError("KeyDescription has too few elements")
    out = {
        "attestation_version": _der_int(seq[0][3]),
        "attestation_security_level": _der_int(seq[1][3]),
        "attestation_challenge": seq[4][3],
    }
    for enforced, is_hw in ((seq[6][3], False), (seq[7][3], True)):
        for cls, _cons, tag, val in _der_children(enforced):
            if cls != 2:          # context-specific only
                continue
            inner = _der_children(val)
            if not inner:
                continue
            if tag == 705:
                out["os_version"] = _der_int(inner[0][3])
            elif tag == 706:
                out["os_patch_level"] = _der_int(inner[0][3])
            elif tag == 718:
                out["vendor_patch_level"] = _der_int(inner[0][3])
            elif tag == 719:
                out["boot_patch_level"] = _der_int(inner[0][3])
            elif tag == 704 and is_hw:
                rot = _der_children(inner[0][3])
                if len(rot) >= 3:
                    out["device_locked"] = rot[1][3] not in (b"", b"\x00")
                    out["verified_boot_state"] = _der_int(rot[2][3])
            elif tag == 709:
                try:
                    app = _der_children(_der_children(inner[0][3])[0][3])
                    pkgs = _der_children(app[0][3])
                    if pkgs:
                        out["package_name"] = _der_children(pkgs[0][3])[0][3].decode(
                            "utf-8", "replace")
                except (ValueError, IndexError):
                    pass
    return out


def _raw_public_key_bits(pub, be):
    """The subjectPublicKey BIT STRING contents — what both the Apple
    credentialId and Forsheur's Android root pin are computed over. NOT the
    SPKI wrapper; hashing that instead yields a different digest that matches
    nothing and looks exactly as plausible."""
    if isinstance(pub, be["ec"].EllipticCurvePublicKey):
        return pub.public_bytes(be["Encoding"].X962,
                                be["PublicFormat"].UncompressedPoint)
    return pub.public_bytes(be["Encoding"].DER, be["PublicFormat"].PKCS1)


def _cert_signed_by(child, issuer, be):
    """True/False for a signature that was checked; raises when it could not be.

    The distinction is the difference between "this chain is forged" and "this
    verifier is too old for this chain". Collapsing them into False would let a
    curve we have not implemented yet be reported as a forgery — an accusation,
    made by our own gap.
    """
    from cryptography.exceptions import InvalidSignature
    pub = issuer.public_key()
    try:
        if isinstance(pub, be["ec"].EllipticCurvePublicKey):
            pub.verify(child.signature, child.tbs_certificate_bytes,
                       be["ec"].ECDSA(child.signature_hash_algorithm))
        else:
            pub.verify(child.signature, child.tbs_certificate_bytes,
                       be["padding"].PKCS1v15(), child.signature_hash_algorithm)
        return True
    except InvalidSignature:
        return False


def _validity(cert):
    """(not_before, not_after) as aware UTC, across `cryptography` versions."""
    try:
        return cert.not_valid_before_utc, cert.not_valid_after_utc
    except AttributeError:                       # cryptography < 42
        tz = datetime.timezone.utc
        return (cert.not_valid_before.replace(tzinfo=tz),
                cert.not_valid_after.replace(tzinfo=tz))


def _walk_chain(certs, at, rep, label, be):
    """Verify each link, and check validity AT `at` — never at "now".

    This distinction is the whole reason the bundle is worth anything in ten
    years. Certificates expire; recordings do not become false when they do.
    The question a reader must answer is "was this chain valid when the notary
    sealed these bytes", and `at` is that instant — carried by a block header
    that is hash-chained, notary-signed and anchored in Bitcoin, so it is not
    our clock either.
    """
    ok = True
    for i in range(len(certs) - 1):
        try:
            good = _cert_signed_by(certs[i], certs[i + 1], be)
        except Exception as e:
            # Not a failure of the chain — a failure of this verifier to read
            # it. Reported as such, and never counted as a broken signature.
            rep.note(f"{label}: link #{i} could not be checked by this verifier "
                     f"({e}) — a signature algorithm it does not implement")
            ok = False
            continue
        if not good:
            rep.bad(f"{label}: certificate #{i} is not signed by #{i + 1}")
            ok = False
    # Does expiry mean anything for THIS chain?
    #
    # Not once it roots in a Google anchor pinned above. Google does not use
    # validity windows as a control in its attestation hierarchy: the leaf it
    # issues is dated 1970-01-01 to 2106-02-07, and on a 2016-era handset both
    # intermediates AND the root expired on 2026-05-24. Those certificates are
    # burned into the device at manufacture and never refreshed, so such a phone
    # can never present a chain that passes an expiry check. Withdrawal here is
    # published in the status list, not encoded in notAfter.
    #
    # Apple's chain is NOT covered: Apple issues real windows, and expiry there
    # keeps its usual meaning.
    google = _google_root_pins(be)
    manufacturer_dates_are_not_a_verdict = bool(certs) and (
        certs[-1].subject == certs[-1].issuer
        and hashlib.sha256(
            _raw_public_key_bits(certs[-1].public_key(), be)).hexdigest() in google)
    if manufacturer_dates_are_not_a_verdict:
        expired = []
        for i, c in enumerate(certs):
            nb, na = _validity(c)
            if at is not None and not (nb <= at <= na):
                expired.append(f"#{i} (to {na:%Y-%m-%d})")
        # Disclosed, never silent: "checked and valid" and "not judged, on
        # purpose" have to stay tellable apart.
        if expired:
            rep.note(f"{label}: expiry is not a verdict on this chain — it roots in a "
                     "Google attestation\n    anchor pinned in this script, and Google does "
                     "not use validity windows as a\n    control here (the leaf it issues "
                     "is dated 1970 to 2106; withdrawal is\n    published in the status "
                     "list instead). Outside their window: "
                     + ", ".join(expired) + ".")
        return ok
    any_outside = False
    for i, c in enumerate(certs):
        nb, na = _validity(c)
        if at is not None and not (nb <= at <= na):
            any_outside = True
            rep.bad(f"{label}: certificate #{i} was not valid at the sealing time "
                    f"({at:%Y-%m-%d %H:%M} UTC; valid {nb:%Y-%m-%d} to {na:%Y-%m-%d})")
            ok = False
    # Said out loud when it actually happened, so the caller's summary never has
    # to claim a check on the chain's behalf.
    if at is not None and not any_outside:
        rep.ok(f"{label}: every certificate was inside its validity window at the "
               "sealing time")
    return ok


def _report_disclosure(kd, rep):
    """What the chain says about the handset, said plainly.

    These fields are published because a signed certificate cannot be redacted
    field by field — remove one and it stops verifying. The patch levels are
    the part that costs the filmer something, so a reader should see that they
    are looking at it rather than have it slip by inside a hex dump.
    """
    boot = {0: "verified (locked bootloader, vendor-signed image)",
            1: "self-signed (custom image, signed by the phone's owner)",
            2: "unverified", 3: "failed"}.get(kd.get("verified_boot_state"))
    if boot:
        rep.ok(f"verified boot state at key generation: {boot}")
    if kd.get("device_locked") is False:
        rep.note("the bootloader was UNLOCKED when this key was generated")
    bits = [f"{k.replace('_', ' ')} {kd[k]}"
            for k in ("os_version", "os_patch_level", "vendor_patch_level",
                      "boot_patch_level") if kd.get(k) is not None]
    if bits:
        print("    The chain discloses the handset's " + ", ".join(bits) + ".")
        print("    That is the filmer's cost for this proof: patch levels say which\n"
              "    known vulnerabilities the phone had not yet fixed. It cannot be\n"
              "    removed without breaking the manufacturer's signature.")


def verify_attestation(root, manifest, device_pubs, seal_at, rep, args):
    """Level 3: walk the manufacturer's chain, offline, to Apple or Google."""
    dev = manifest.get("device") or {}
    att = dev.get("attestation")
    if not att:
        rep.note("this bundle carries no attestation section — it was produced by "
                 "a server from before manufacturer chains travelled with the "
                 "evidence")
        return

    state = att.get("state")
    if state in ("withheld", "withheld_by_filmer"):
        # Both spellings accepted: `withheld_by_filmer` shipped for a few hours
        # and credited a decision nobody could make. A bundle written then is
        # not wrong about the CHAIN, only about who held it back.
        rep.note("the manufacturer chain exists and was not published. It cannot "
                 "be redacted field by field — its contents sit inside a "
                 "certificate the manufacturer signed — and publishing it "
                 "discloses the handset's security patch levels, so holding it "
                 "back is meant to be the filmer's decision. Forsheur offers no "
                 "way to make that decision yet, so a chain withheld today was "
                 "withheld by Forsheur, not by the person filming. Either way it "
                 "is not the same as no chain having been captured.")
        return
    if state == "not_captured":
        rep.note("no manufacturer chain was captured for this device: its "
                 "certificate predates the day chains were kept, or the platform "
                 "produced none. Not a finding against the device.")
        return

    be = _x509_backend()
    if be is None:
        rep.note("install the `cryptography` package (pip install cryptography) "
                 "to check the manufacturer chain offline. Everything above is "
                 "unaffected — the media verdict does not depend on it.")
        return

    x509m = be["x509"]
    nonce_hex = att.get("nonce_hex")
    cert_body_b64 = dev.get("cert_body_b64")
    cdh = None
    if nonce_hex and cert_body_b64:
        cdh = hashlib.sha256(bytes.fromhex(nonce_hex)
                             + base64.b64decode(cert_body_b64)).digest()

    files = att.get("files") or {}

    def _load(rel):
        with open(os.path.join(root, rel), "rb") as f:
            return f.read()

    # ── Android: the signing key's own chain ────────────────────────────
    sk_files = files.get("signing_key_chain") or []
    if sk_files:
        try:
            ders = [_load(r) for r in sk_files]
            certs = [x509m.load_der_x509_certificate(d) for d in ders]
        except (OSError, ValueError) as e:
            rep.bad(f"signing-key chain could not be read: {e}")
            certs = []
        if len(certs) < 2:
            rep.bad("signing-key chain is too short to be an attestation "
                    "(a lone self-signed certificate is what Keystore returns "
                    "when no challenge was given)")
        elif _walk_chain(certs, seal_at, rep, "signing-key chain", be):
            rep.ok(f"signing-key chain: {len(certs)} certificates, each signed by the next")
            leaf_bits = _raw_public_key_bits(certs[0].public_key(), be)
            # Bound on every path: the anchoring verdict below reads it to tell
            # a software chain's root apart from an unknown one, and it is only
            # assigned inside the branch where the leaf matched.
            kd = None
            # The leaf's key must BE the key that signed the chunks. A chain
            # attesting some other key of the same phone verifies perfectly and
            # says nothing about these bytes.
            if not device_pubs:
                rep.note("no chunk carried a device key — nothing to tie the "
                         "chain to")
            elif leaf_bits != next(iter(device_pubs)):
                rep.bad("the attestation chain attests a DIFFERENT key than the "
                        "one that signed these chunks")
            else:
                rep.ok("the chain's leaf public key IS the key that signed every "
                       "chunk here")
                try:
                    ext = certs[0].extensions.get_extension_for_oid(
                        x509m.ObjectIdentifier(KEY_DESCRIPTION_OID))
                    kd = parse_key_description(ext.value.value)
                except Exception as e:
                    rep.bad(f"Android KeyDescription unreadable: {e}")
                    kd = None
                if kd is not None:
                    if nonce_hex is None:
                        rep.note("no enrolment nonce in this bundle — the chain "
                                 "cannot be shown to answer THIS certificate")
                    elif kd["attestation_challenge"] != bytes.fromhex(nonce_hex):
                        rep.bad("the chain answers a different challenge than this "
                                "certificate's — it may be a genuine attestation "
                                "replayed from elsewhere")
                    else:
                        rep.ok("the chain answers the exact challenge this "
                               "certificate was issued against (not a replay)")
                    level = {0: "software", 1: "a protected area of the phone's "
                                               "processor (TEE)",
                             2: "a StrongBox secure element"}.get(
                                 kd["attestation_security_level"], "an unknown level")
                    if kd["attestation_security_level"] == 0:
                        rep.note("the chain states the signing key was generated in "
                                 "SOFTWARE, not in a secure element — the signatures "
                                 "are just as valid, but someone who took the phone "
                                 "could have copied that key")
                    else:
                        rep.ok(f"Google's chain states this key was generated inside "
                               f"{level} and cannot leave it")
                    pkg = att.get("android_package")
                    if pkg and kd.get("package_name") and kd["package_name"] != pkg:
                        rep.bad("the chain was issued to a different app "
                                f"({kd['package_name']}) than this bundle names")
                    elif kd.get("package_name"):
                        rep.ok(f"issued to the app {kd['package_name']}")
                    _report_disclosure(kd, rep)
            # The root travelling inside the chain anchors nothing by itself.
            # What anchors it is the root Google publishes, pinned in this
            # script — and a reader who trusts neither this script nor Google's
            # page can bring their own copy with --attest-root.
            root_fp = hashlib.sha256(
                _raw_public_key_bits(certs[-1].public_key(), be)).hexdigest()
            reader = _load_reader_roots(args, be)
            google = _google_root_pins(be)
            if root_fp in reader:
                rep.ok("the chain's root is one you supplied with --attest-root")
            elif root_fp in google:
                rep.ok("the chain's root is a Google attestation root published at\n"
                       f"      {GOOGLE_ROOTS_URL}\n"
                       "    and pinned in this script (SHA-256 "
                       f"{root_fp[:16]}…)")
            elif kd is not None and kd.get("attestation_security_level") == 0:
                # A software chain roots in Android's SOFTWARE attestation root,
                # which is by construction not a hardware anchor. Saying so is
                # not the same as saying the chain failed — the handset is
                # telling the truth about having no secure element.
                rep.note("this chain roots outside Google's hardware anchors, which "
                         "is expected\n    for a SOFTWARE attestation: fingerprint "
                         f"SHA-256 {root_fp}")
            else:
                rep.bad("this chain claims hardware backing but its root is NOT one "
                        "of the roots\n    Google publishes, nor one you supplied. "
                        f"Root fingerprint SHA-256\n      {root_fp}\n"
                        f"    Check it against {GOOGLE_ROOTS_URL} — until it matches, "
                        "the chain is\n    internally consistent and vouched for by "
                        "nobody.")
            print("    Revocation cannot be checked here: Google's status list is "
                  "online-only\n    and unsigned. See the dated answer below.")

    # ── Apple: App Attest ───────────────────────────────────────────────
    apple_rel = files.get("apple_appattest")
    if apple_rel:
        try:
            obj = cbor_decode(_load(apple_rel))
        except (OSError, ValueError) as e:
            rep.bad(f"App Attest object could not be read: {e}")
            obj = None
        if isinstance(obj, dict):
            if obj.get("fmt") != "apple-appattest":
                rep.bad("App Attest object does not announce fmt=apple-appattest")
            auth_data = obj.get("authData") or b""
            x5c = (obj.get("attStmt") or {}).get("x5c") or []
            try:
                certs = [x509m.load_der_x509_certificate(d) for d in x5c]
            except ValueError as e:
                rep.bad(f"App Attest x5c is not valid DER: {e}")
                certs = []
            if not certs or len(auth_data) < 55 + 32:
                rep.bad("App Attest object is malformed (missing chain or "
                        "attested credential data)")
            else:
                # Apple does not put its root in x5c, so anchoring is a step of
                # its own — and the root comes from this script, never from the
                # archive being examined. Named `apple_root`, not `root`: the
                # bundle directory is also bound to `root` here, and a closure
                # that reads files from it would have followed the rebinding.
                apple_root = x509m.load_pem_x509_certificate(
                    APPLE_APP_ATTEST_ROOT_PEM.encode())
                if _walk_chain(certs + [apple_root], seal_at, rep,
                               "App Attest chain", be):
                    rep.ok(f"App Attest chain: {len(certs)} certificates, rooted in the Apple "
                           "App Attestation Root CA pinned inside this script")
                aaguid = auth_data[37:53]
                env = {AAGUID_PROD: "production",
                       AAGUID_DEV: "development (an Xcode build, not the App Store)"}.get(
                           bytes(aaguid))
                if env is None:
                    rep.bad("App Attest object carries an unknown AAGUID")
                elif env.startswith("development"):
                    rep.note(f"this attestation came from Apple's {env}")
                cred_id = auth_data[55:55 + 32]
                leaf_bits = _raw_public_key_bits(certs[0].public_key(), be)
                if cred_id != hashlib.sha256(leaf_bits).digest():
                    rep.bad("credentialId does not match the leaf's public key")
                app_id = att.get("apple_app_id")
                if app_id:
                    if auth_data[:32] != hashlib.sha256(app_id.encode()).digest():
                        rep.bad("the object was produced for a different app than "
                                "this bundle names")
                    else:
                        rep.ok(f"produced for the app {app_id} — a name this bundle "
                               "supplies, and which you can check against the app "
                               "you installed")
                if cdh is None:
                    rep.note("no enrolment nonce in this bundle — the object cannot "
                             "be tied to this certificate")
                else:
                    want = hashlib.sha256(auth_data + cdh).digest()
                    try:
                        ext = certs[0].extensions.get_extension_for_oid(
                            x509m.ObjectIdentifier(APP_ATTEST_NONCE_OID))
                        found = want in bytes(ext.value.value)
                    except Exception:
                        found = False
                    if found:
                        rep.ok("Apple's attestation is bound to THIS certificate "
                               "body: a genuine Apple device running this app "
                               "produced the very certificate that names the "
                               "signing key")
                    else:
                        rep.bad("Apple's nonce extension does not match this "
                                "certificate body — the object belongs to another "
                                "registration")
                # Said next to the success, deliberately. This is the exact
                # sentence the audit found the product blurring for a year.
                print("    Apple attests its OWN App Attest key, never one you chose:\n"
                      "    this proves the device and the app, and says NOTHING about\n"
                      "    where the chunk-signing key lives. On iPhone that placement\n"
                      "    is the phone's word, which is why it reads `declared`.")

    # ── The dated word about revocation ─────────────────────────────────
    rev = att.get("revocation")
    if rev:
        outcome = rev.get("outcome")
        when = str(rev.get("checked_at", ""))[:19].replace("T", " ")
        if outcome == "listed":
            rep.bad(f"Google's status list named this chain as REVOKED when Forsheur "
                    f"asked, on {when}")
        elif outcome == "clear":
            rep.note(f"Forsheur asked Google's attestation status list on {when} and "
                     "was told none of these certificates was withdrawn. That is a "
                     "DATED WORD, not a proof: the list is unsigned and online-only, "
                     "so nobody can reproduce it here — including us, now.")
        else:
            rep.note(f"Forsheur could not reach Google's status list at enrolment "
                     f"({outcome}); nothing is claimed either way about revocation")


def _google_root_pins(be):
    """Fingerprints of the Google roots pinned in this script.

    Computed from the certificates rather than hard-coded as hex, so the value
    checked and the value a reader can inspect are the same bytes. A hex
    constant sitting next to a PEM invites the two to drift apart, and the one
    that drifts is always the one nobody re-derives.
    """
    out = set()
    for pem in GOOGLE_ATTESTATION_ROOTS_PEM:
        cert = be["x509"].load_pem_x509_certificate(pem.encode())
        out.add(hashlib.sha256(_raw_public_key_bits(cert.public_key(), be)).hexdigest())
    return out


def _load_reader_roots(args, be):
    """Root fingerprints the READER brought, from --attest-root."""
    out = set()
    for path in getattr(args, "attest_root", None) or []:
        try:
            with open(path, "rb") as f:
                raw = f.read()
            cert = (be["x509"].load_pem_x509_certificate(raw) if b"-----BEGIN" in raw
                    else be["x509"].load_der_x509_certificate(raw))
            out.add(hashlib.sha256(
                _raw_public_key_bits(cert.public_key(), be)).hexdigest())
        except Exception as e:
            print(f"  ! --attest-root {path}: {e}")
    return out


def verify_device_chain(manifest, device_pubs, rep):
    """Walk the chain from the key that signed the chunks up to the account key.

    Four links, and this function checks the last two — the chunk signature and
    the key's presence inside the signed envelope are checked per chunk above:

      1. sig_device over H_chunk        "these bytes were signed by key K"
      2. K appears in the signed envelope   "K cannot have been substituted"
      3. cert_body contains K, signed by M  "the holder of M authorised K"   <- here
      4. M is the account's master key      "and M is that account"          <- here

    Until 2026-09-07 the bundle carried only 1 and 2, so offline it stopped at
    "an anonymous key signed this" while the public web page proved the whole
    chain. The artefact meant to outlive the infrastructure proved LESS than the
    site that depends on it — the largest remaining finding of the audit.

    WHAT THIS DOES NOT DO, and must never be described as doing: identify
    anybody. `master_sign_pub` is a number. The link between it and a person
    lives on a server and is meant to stay there. What closing this chain buys
    is authenticity and CONSISTENCY — the same signer behind a body of work,
    demonstrable without us — not identity.
    """
    dev = manifest.get("device")
    if not dev or not dev.get("cert_body_b64"):
        rep.note("no device certificate in this bundle — the chain stops at the "
                 "signing key, which nothing here ties to an account")
        return

    body = base64.b64decode(dev["cert_body_b64"])
    # Two layouts, told apart by the FIRST byte and never by the total length.
    # Measuring instead of reading is what breaks the day a third layout arrives
    # with a familiar width — and it already misfired once, in the player, which
    # read a P-256 body's validity window out of the middle of its public key.
    key_len = {0x01: 32, 0x02: 65}.get(body[0] if body else None)
    if key_len is None:
        rep.note(f"certificate body announces version {body[0] if body else '?'}, "
                 "which this verifier does not know — chain not checked")
        return
    key_at = 1 + 4 + 16
    issued_at = key_at + key_len
    if len(body) != issued_at + 16:
        rep.bad("certificate body length disagrees with the version it announces")
        return

    cert_key = body[key_at:issued_at]

    # The certificate has to name THE key that signed the chunks. A certificate
    # for some other key of the same account would verify perfectly on its own
    # and prove nothing about these bytes.
    if not device_pubs:
        rep.note("no chunk carried a device key — nothing to tie the certificate to")
        return
    if len(device_pubs) > 1:
        rep.bad("chunks in this session were signed by more than one device key")
        return
    if cert_key != next(iter(device_pubs)):
        rep.bad("the certificate attests a DIFFERENT key than the one that signed "
                "these chunks")
        return
    rep.ok("the certificate names exactly the key that signed these chunks")

    def _i64(off):
        v = int.from_bytes(body[off:off + 8], "big")
        return v - (1 << 64) if v >> 63 else v

    iss, exp = _i64(issued_at), _i64(issued_at + 8)
    now = int(datetime.datetime.now(datetime.timezone.utc).timestamp())
    if now < iss:
        rep.bad("device certificate is not valid yet")
    elif now >= exp:
        # An expired certificate is not a failed one. The chunks were sealed
        # while it was live, and the notary chain is what dates them — saying
        # FAIL here would report an aged certificate as a forgery.
        rep.note("device certificate has expired since capture "
                 f"(valid {datetime.datetime.fromtimestamp(iss, datetime.timezone.utc):%Y-%m-%d} "
                 f"to {datetime.datetime.fromtimestamp(exp, datetime.timezone.utc):%Y-%m-%d})")

    sig_b64 = dev.get("user_signature_b64")
    master_b64 = (manifest.get("user") or {}).get("master_sign_pub_b64")
    if not sig_b64 or not master_b64:
        # Attest-only certificate: the account never signed for this device. Not
        # a defect and not something to leave unsaid — it is exactly the
        # difference the public page calls `attested_only`.
        rep.note("this certificate carries no account signature (attest-only): the "
                 "device proved its own integrity, but the account never vouched "
                 "for it")
        return

    if ed25519_verify(base64.b64decode(master_b64), base64.b64decode(sig_b64), body):
        rep.ok("the account's master key signed this certificate — chain closed: "
               "bytes → device key → certificate → account")
        # Said in the same breath as the success, deliberately. A reader who
        # stops at the green line must not walk away believing more than this.
        print("    The account is a public key, not a person: this proves one "
              "consistent\n    signer, not who they are.")
    else:
        rep.bad("the account's signature over the device certificate is INVALID")

    level = dev.get("signing_key_level")
    if level:
        proof = dev.get("signing_key_proof")
        where = {"secure_enclave": "the phone's Secure Enclave",
                 "strongbox": "a StrongBox secure element",
                 "tee": "a protected area of the phone's processor",
                 "software": "the app's ordinary storage"}.get(level, level)
        if level == "software":
            rep.note(f"the signing key was held in {where}, not a secure element — "
                     "the signatures are just as valid, but someone who took the "
                     "phone could have copied that key")
        else:
            # `attested` and `declared` are different evidence and never share a
            # sentence: one is a manufacturer's chain, the other the phone's word.
            #
            # And `attested` is Forsheur's verdict, reported here — not a check
            # made here. Until 2026-09-09 this line printed "the manufacturer's
            # chain proves it" on the strength of that string alone, in bundles
            # that carried no chain at all: the reader was told a proof existed
            # and handed nothing to examine. The chain, when it travels, is
            # checked in the "Manufacturer attestation" section below, and THAT
            # is where a claim about it belongs.
            chain_here = ((manifest.get("device") or {}).get("attestation") or {}
                          ).get("state") == "published"
            how = ("recorded as proven by a manufacturer chain — see below, where "
                   "that chain is actually checked" if proof == "attested" and chain_here
                   else "Forsheur's verdict, recorded at enrolment; the chain that "
                        "produced it is not in this bundle" if proof == "attested"
                   else "as reported by the device — this bundle carries no proof "
                        "of that placement")
            rep.ok(f"the signing key was held in {where} ({how})")


def load_bundle_dir(arg):
    if os.path.isdir(arg):
        base = arg
    elif zipfile.is_zipfile(arg):
        dest = os.path.splitext(os.path.abspath(arg))[0] + "-extracted"
        print(f"Extracting {arg} -> {dest}")
        with zipfile.ZipFile(arg) as z:
            z.extractall(dest)
        base = dest
    else:
        sys.exit(f"error: {arg} is neither a directory nor a zip file")
    # The archive has a single forsheur-evidence-* root dir.
    if os.path.exists(os.path.join(base, "manifest.json")):
        return base
    subs = [d for d in os.listdir(base) if os.path.isdir(os.path.join(base, d))]
    for s in subs:
        if os.path.exists(os.path.join(base, s, "manifest.json")):
            return os.path.join(base, s)
    sys.exit("error: manifest.json not found in bundle")


def main():
    ap = argparse.ArgumentParser(description="Verify a Forsheur evidence bundle offline.")
    # Before the positional, so `--version` answers without a bundle: someone
    # comparing their copy against the published releases has a hash and no
    # archive to hand, and making them invent one to read a version number
    # would be an obstacle with nothing behind it.
    ap.add_argument("--version", action="version",
                    version=f"verify_bundle.py {VERIFIER_VERSION}")
    ap.add_argument("bundle", help="bundle .zip or extracted directory")
    ap.add_argument("--extract", action="store_true", help="write verified media streams to extracted/")
    ap.add_argument("--dek", action="store_true",
                    help="decrypt an encrypted session; prompts (hidden input) for the 32-byte "
                         "session DEK hex — never pass a key on the command line")
    ap.add_argument("--id-priv", action="store_true",
                    help="decrypt with your X25519 identity private key; prompts (hidden input) for "
                         "it (64 hex chars or a BIP39 mnemonic), opening a sealed DEK from the bundle")
    ap.add_argument("--id-priv-file", metavar="PATH",
                    help="non-interactive alternative: read the identity key from a file "
                         "(keeps it out of shell history)")
    ap.add_argument("--attest-root", metavar="PATH", action="append",
                    help="add a root certificate YOU obtained from Google (PEM or DER) "
                         "to the anchors this script already pins. Repeatable, and needed "
                         "only if you would rather not take this script's word for what "
                         "Google publishes, or if Google has added a root newer than this "
                         "copy. Both manufacturers' published roots are pinned inside the "
                         "script; a root arriving inside the archive being checked anchors "
                         "nothing and never counts.")
    ap.add_argument("--json", metavar="PATH",
                    help="also write a machine-readable summary to PATH. The human "
                         "text on stdout stays exactly as it is and remains the "
                         "authoritative account; this is the same run, restated for "
                         "a program that needs to quote it without parsing prose.")
    args = ap.parse_args()

    root = load_bundle_dir(args.bundle)
    rep = Report()

    def jload(rel):
        with open(os.path.join(root, rel), "rb") as f:
            return json.load(f)

    manifest = jload("manifest.json")
    session = manifest["session"]
    # `== "aes-gcm-256"`, not `!= "none"`. Three transmission modes exist and
    # only ONE of them puts ciphertext in this archive:
    #
    #   none             clear      — never sealed
    #   box-seal-x25519  transport  — the phone sealed each payload to the
    #                                 PLATFORM's key so the recording was never
    #                                 at rest in cleartext on the device; the
    #                                 server opened it on arrival, and the
    #                                 payloads here ARE the media
    #   aes-gcm-256      e2e        — the DEK is sealed to USERS, no server
    #                                 holds a key, and these bytes stay
    #                                 ciphertext until someone opens them
    #
    # Reading transport as encrypted made this script tell the holder of a
    # perfectly readable bundle that their media was "ciphertext, nothing to
    # extract without a key", and send them looking for a key that does not
    # exist for that session — while the README in the same archive correctly
    # said the session was cleartext. `evidence_bundle.rs` and
    # `v2_manifest.rs` already make this distinction; this line did not.
    encrypted = session.get("encryption", "none") == "aes-gcm-256"
    # Printed first, and printed even when everything below fails: a reader
    # quoting this transcript is entitled to know which copy of the verifier
    # produced it without trusting the part of it that could be forged.
    _self = _self_sha256()
    print(f"verify_bundle.py {VERIFIER_VERSION}"
          + (f"  sha256={_self}" if _self else "  (sha256 unavailable)"))
    print(f"Session {session['session_id']}  chunks={session['chunk_count']}  "
          f"encryption={session.get('encryption')}")

    # Every device key that actually verified a chunk. A set, so a session
    # signed by two different keys is visible as such rather than averaged into
    # whichever one the certificate happens to name.
    seen_device_pubs = set()

    keys = {}
    for k in jload(manifest["notary"]["keys"])["keys"]:
        keys[k["key_id"]] = bytes.fromhex(k["public_key"])
    print(f"Notary keys: {len(keys)} loaded from bundle "
          "(cross-check /.well-known/forsheur-notary-keys.json if desired)\n")

    # Optional decryption key for an encrypted session (out-of-band from the user).
    dek = None
    if encrypted:
        dek = resolve_dek(root, manifest, args)
        if dek is not None:
            print("Decryption key resolved — encrypted payloads will be decrypted and each "
                  "checked against\nits device-signed plaintext hash.\n")
        elif args.extract:
            print("Encrypted session, no key supplied — pass --dek or --id-priv to decrypt.\n")

    # ── Chain segment (anchor path) ────────────────────────────────────────
    headers = {}
    cover_block = manifest["notary"].get("cover_block")
    ap_rel = manifest["notary"].get("anchor_path")
    if ap_rel:
        print("Chain segment:")
        apj = jload(ap_rel)
        blocks = apj.get("blocks", [])
        prev_hash = None
        chain_ok = True
        for b in blocks:
            idx = b["index"]
            bh = block_hash_of(idx, bytes.fromhex(b["prev_block_hash"]),
                               bytes.fromhex(b["merkle_root"]), b["seal_time"])
            if bh.hex() != b["block_hash"]:
                rep.bad(f"block #{idx}: recomputed hash mismatch")
                chain_ok = False
            key = keys.get(b["signing_key_id"])
            if not (key and ed25519_verify(key, bytes.fromhex(b["signature"]), bh)):
                rep.bad(f"block #{idx}: notary signature invalid")
                chain_ok = False
            if prev_hash is not None and b["prev_block_hash"] != prev_hash:
                rep.bad(f"block #{idx}: chain link broken (prev != previous block hash)")
                chain_ok = False
            prev_hash = b["block_hash"]
            headers[idx] = b
        if chain_ok and blocks:
            rep.ok(f"{len(blocks)} block headers recomputed, signed and chained "
                   f"(#{blocks[0]['index']} .. #{blocks[-1]['index']})")
    else:
        rep.note("no anchor-path in bundle (chunks not sealed yet?)")

    # ── Per-chunk verification ─────────────────────────────────────────────
    verified_payloads = []  # (seq, chunk_id, payload_bytes) for --extract
    pair_dirs = []          # per-chunk cipher/plain dumps written under --extract
    frozen_all = []         # (t_us, held_frame, missed) disclosed by the device
    frozen_reported = False  # did ANY chunk carry the stream? absence ≠ clean
    # Front camera (dual-cam): a second, independent disclosure. The same
    # absence ≠ clean rule applies per camera — a single-camera recording
    # simply carries no front stream, and nothing is claimed about it.
    frozen_front_all = []
    frozen_front_reported = False
    time_all = []            # (t_us, source, value_us, uncertainty_us, age_us)
    time_reported = False    # did ANY chunk declare its clocks? absence ≠ agreement
    fraud_all = []           # (t_us, seq, score, model_version, frames_scored)
    fraud_reported = False   # did the detector run at all? absence ≠ clean
    for c in manifest["chunks"]:
        cid = c["chunk_id"]
        print(f"\nChunk seq={c['seq']} {cid}:")
        payload = None
        ppath = os.path.join(root, c["files"]["payload"])
        if os.path.exists(ppath):
            with open(ppath, "rb") as f:
                payload = f.read()
        epath = os.path.join(root, c["files"]["envelope"])
        envelope = None
        if os.path.exists(epath):
            with open(epath, "rb") as f:
                envelope = f.read()

        prpath = os.path.join(root, c["files"]["proof"])
        proofs = []
        if os.path.exists(prpath):
            with open(prpath, "rb") as f:
                pj = json.load(f)
            if isinstance(pj, list):
                proofs = [p for p in pj if p.get("status") == "sealed"]
                if not proofs and pj:
                    rep.note("notary entry exists but is not sealed yet")
            else:
                rep.note(f"no notary proof: {pj.get('error', 'unknown')}")

        if payload is None:
            rep.bad("payload.bin missing")
            continue

        chunk_all_ok = True
        for proof in proofs or [None]:
            if proof is None:
                # No sealed proof — still bind media to the device signature if
                # the enrichment material is present in a non-sealed entry.
                rep.note("verifying without notary seal (media+signature only unavailable)")
                chunk_all_ok = False
                break

            h_received = proof.get("h_received")
            if h_received is None:
                rep.note("no recompute material in proof; skipping media binding")
                chunk_all_ok = False
                continue

            # 1. media bytes == the hash the device committed to
            #
            # Which hash depends on what these bytes ARE. `h_received` commits
            # to what left the phone; `plaintext_hash` to the payload before
            # encryption. Identical for a plain recording. They differ when the
            # phone encrypted a PUBLIC session for transport — so its video was
            # never at rest in cleartext on the device — and the server opened
            # it on arrival and stored the cleartext. Both values sit in the
            # same device-signed envelope, and step 2 below re-derives H_chunk
            # from `h_received` regardless, so a wrong claim here still fails
            # the signature.
            stored_is_plaintext = bool(proof.get("payload_is_plaintext"))
            bound_hash = (proof.get("plaintext_hash") if stored_is_plaintext
                          else h_received)
            if not bound_hash:
                rep.bad("payload declared as decrypted but no plaintext hash to bind it to")
                chunk_all_ok = False
                continue
            if hashlib.sha256(payload).hexdigest() == bound_hash:
                rep.ok("sha256(payload) == "
                       + ("plaintext_hash (stored decrypted)" if stored_is_plaintext
                          else "h_received"))
            else:
                rep.bad("payload bytes do not match the hash the device signed")
                chunk_all_ok = False
                continue

            # 2. envelope -> H_env -> H_chunk == notarized commitment
            if envelope is None:
                rep.bad("envelope.cbor missing")
                chunk_all_ok = False
                continue
            disclosed = frozen_frames_from_envelope(envelope)
            if disclosed is not None:
                frozen_reported = True
                frozen_all.extend(disclosed)
            disclosed_front = frozen_frames_from_envelope(
                envelope, "video.front.frozen.v1")
            if disclosed_front is not None:
                frozen_front_reported = True
                frozen_front_all.extend(disclosed_front)
            clocks = time_refs_from_envelope(envelope)
            if clocks is not None:
                time_reported = True
                time_all.extend(clocks)
            verdicts = fraud_verdicts_from_envelope(envelope)
            if verdicts is not None:
                fraud_reported = True
                fraud_all.extend(verdicts)
            # The plaintext hash arrived in the proof file, i.e. from the
            # server. Before it may stand as the binding for these bytes it has
            # to appear verbatim inside the envelope the device signed —
            # otherwise a server that swapped the payload could have shipped a
            # matching hash to go with it. Same guard the decryption path below
            # applies before trusting a revealed cleartext.
            if stored_is_plaintext and bytes.fromhex(bound_hash) not in envelope:
                rep.bad("the plaintext hash these bytes matched is NOT inside the signed envelope")
                chunk_all_ok = False
                continue
            h_env = hashlib.sha256(envelope).digest()
            h_chunk = hashlib.sha256(h_env + bytes.fromhex(h_received)).digest()
            if h_chunk.hex() == proof["commitment_hash"]:
                rep.ok("H_chunk == notarized commitment")
            else:
                rep.bad("H_chunk != commitment_hash (envelope or payload tampered)")
                chunk_all_ok = False
                continue

            # 3. device signature over H_chunk, pubkey pinned inside the envelope
            pub = bytes.fromhex(proof["device_pubkey"])
            if pub not in envelope:
                rep.bad("device pubkey not present in the signed envelope")
                chunk_all_ok = False
            elif device_sig_verify(pub, bytes.fromhex(proof["device_signature"]), h_chunk):
                rep.ok("device %s signature valid"
                       % ("Ed25519" if len(pub) == 32 else "ECDSA P-256"))
                seen_device_pubs.add(pub)
            else:
                rep.bad("device signature INVALID")
                chunk_all_ok = False
                continue

            # 4. leaf -> Merkle root -> block hash -> notary signature
            plaintext = proof.get("plaintext_hash")
            lh = leaf_hash(proof["entry_type"], proof["ref_id"], proof["received_at"],
                           bytes.fromhex(proof["commitment_hash"]),
                           bytes.fromhex(plaintext) if plaintext else None)
            if lh.hex() != proof["leaf_hash"]:
                rep.bad("recomputed leaf_hash mismatch")
                chunk_all_ok = False
                continue
            blk = proof["block"]
            path = [bytes.fromhex(x) for x in (proof.get("merkle_path") or [])]
            try:
                mroot = root_from_path(lh, proof["leaf_index"], blk["entry_count"], path)
            except ValueError as e:
                rep.bad(f"merkle path invalid: {e}")
                chunk_all_ok = False
                continue
            if mroot.hex() != blk["merkle_root"]:
                rep.bad("merkle root mismatch")
                chunk_all_ok = False
                continue
            bh = block_hash_of(blk["index"], bytes.fromhex(blk["prev_block_hash"]),
                               mroot, blk["seal_time"])
            if bh.hex() != blk["block_hash"]:
                rep.bad("block hash mismatch")
                chunk_all_ok = False
                continue
            key = keys.get(blk["signing_key_id"])
            if key and ed25519_verify(key, bytes.fromhex(blk["signature"]), bh):
                rep.ok(f"sealed in block #{blk['index']} — Merkle + notary signature valid")
            else:
                rep.bad("notary signature on block INVALID")
                chunk_all_ok = False
                continue

            # 5. this block is inside the verified chain segment
            hdr = headers.get(blk["index"])
            if hdr is None:
                rep.note(f"block #{blk['index']} outside bundled chain segment")
            elif hdr["block_hash"] != blk["block_hash"]:
                rep.bad(f"block #{blk['index']} differs from chain-segment header")
                chunk_all_ok = False

        # 7. Optional decryption, with the FULL two-sided hash guarantee:
        #      (step 1 above) sha256(ciphertext) == h_received  — the encrypted
        #        bytes are exactly what the device signed and the notary sealed;
        #      (here)         sha256(plaintext)  == the hash the PHONE promised
        #        for the pre-encryption bytes.
        #    That promised hash (payload_meta.hash_plaintext) lives INSIDE the
        #    device-signed envelope, so we first bind the notary's plaintext_hash
        #    to the envelope (it must appear verbatim in the signed bytes); then a
        #    match after decryption proves the revealed cleartext is precisely the
        #    original the device attested — a wrong key/decoy/tamper fails loudly.
        extract_payload = payload
        if encrypted and dek is not None and chunk_all_ok and proofs:
            iv_hex = c.get("iv")
            plaintext_hash = next((p.get("plaintext_hash") for p in proofs
                                   if p.get("plaintext_hash")), None)
            h_received_hex = next((p.get("h_received") for p in proofs
                                   if p.get("h_received")), None)
            if not iv_hex:
                rep.bad("encrypted chunk has no IV in the manifest — cannot decrypt")
                chunk_all_ok = False
            elif not plaintext_hash:
                rep.note("proof carries no plaintext hash — cannot confirm the decrypted bytes")
                chunk_all_ok = False
            elif envelope is not None and bytes.fromhex(plaintext_hash) not in envelope:
                rep.bad("notarized plaintext hash is NOT the one inside the device-signed envelope")
                chunk_all_ok = False
            else:
                try:
                    clear = aesgcm_decrypt(dek, iv_hex, payload)
                except Exception as e:  # noqa: BLE001 — InvalidTag etc.
                    rep.bad(f"AES-GCM decryption failed ({type(e).__name__}) — wrong DEK or IV")
                    chunk_all_ok = False
                    clear = None
                if clear is not None:
                    if hashlib.sha256(clear).hexdigest() == plaintext_hash:
                        rep.ok("decrypted; sha256(plaintext) == the plaintext hash the phone signed")
                        extract_payload = clear
                        if args.extract:
                            pair_dirs.append(write_decrypted_pair(
                                root, c["seq"], cid, clear,
                                h_received_hex, plaintext_hash, c["files"]["payload"]))
                    else:
                        rep.bad("decrypted bytes do NOT match the phone's signed plaintext hash")
                        chunk_all_ok = False

        if chunk_all_ok and proofs:
            verified_payloads.append((c["seq"], cid, extract_payload))

    # ── Device certificate chain ───────────────────────────────────────────
    #
    # After the chunks, because it needs to know WHICH key signed them: a
    # certificate that verifies against the account but names some other key
    # would prove nothing about these bytes.
    print("\nDevice certificate:")
    verify_device_chain(manifest, seen_device_pubs, rep)

    # ── Manufacturer attestation ───────────────────────────────────────────
    #
    # Checked AT the sealing time, not now. The earliest block the notary sealed
    # for this session is the instant these bytes provably existed, and it is
    # anchored outside us (chain -> Bitcoin, Roughtime). Using the reader's
    # clock instead would fail a perfectly good recording the day a certificate
    # expires — which is every recording, eventually.
    seal_at = None
    if headers:
        seal_us = min(h["seal_time"] for h in headers.values())
        seal_at = datetime.datetime.fromtimestamp(seal_us / 1_000_000,
                                                  datetime.timezone.utc)
    print("\nManufacturer attestation:")
    if seal_at is None:
        rep.note("no sealed block in this bundle, so there is no anchored instant "
                 "to check certificate validity against — the chain below is "
                 "checked for structure only")
    verify_attestation(root, manifest, seen_device_pubs, seal_at, rep, args)

    # ── Bitcoin anchor on the cover block ──────────────────────────────────
    print("\nBitcoin anchor:")
    ots_files = manifest["notary"].get("ots_files", {})
    if cover_block is not None and str(cover_block) in ots_files:
        rel = ots_files[str(cover_block)]
        opath = os.path.join(root, rel)
        with open(opath, "rb") as f:
            ots_bytes = f.read()
        hdr = headers.get(cover_block)
        cover_hash = hdr["block_hash"] if hdr else None
        info = ots_info(ots_bytes)
        if info and cover_hash:
            initial, results = info
            if initial.hex() != cover_hash:
                rep.bad(".ots digest != cover block hash")
            elif results:
                rep.ok(f".ots operations executed: cover block #{cover_block} commits to "
                       f"Bitcoin block(s) {', '.join(str(h) for h, _ in results)}")
                print("    The proof is complete if the computed merkle root below matches")
                print("    the 'Merkle Root' field of that Bitcoin block header — one 32-byte")
                print("    public value, no blockchain download needed.")
                for h, dg in results:
                    print(f"\n      Bitcoin block {h}: expected merkle root =")
                    print(f"        {dg[::-1].hex()}")
                    print("      Compare against the 'Merkle root' field on independent explorers:")
                    print(f"        https://mempool.space/block/{h}?showDetails=true#details")
                    print(f"        https://blockstream.info/block-height/{h}  (click 'Details')")
                    print(f"        https://www.blockchain.com/explorer/blocks/btc/{h}  (abbreviated; click to copy)")
                print("\n    Or, fully trustless, via your own node:")
                print("      bitcoin-cli getblockheader $(bitcoin-cli getblockhash <height>)")
            else:
                rep.note(".ots is a calendar receipt (Bitcoin confirmation pending); re-download later")
        elif info is None:
            rep.note("could not parse .ots (try `ots info` from opentimestamps-client)")

        if cover_hash and shutil.which("ots"):
            print("  running `ots verify` (official client; needs a Bitcoin node for full trustlessness)...")
            r = subprocess.run(["ots", "verify", "-d", cover_hash, opath],
                               capture_output=True, text=True)
            out = (r.stdout + r.stderr).strip()
            for line in out.splitlines():
                print("    " + line)
            if "Success!" not in out:
                # Node-less mode: the official client executes the .ots operations
                # itself and prints the merkle root to check manually — an
                # independent cross-check of the value computed above.
                print("  no Bitcoin node — official client in node-less mode (`ots --no-bitcoin verify`):")
                r2 = subprocess.run(["ots", "--no-bitcoin", "verify", "-d", cover_hash, opath],
                                    capture_output=True, text=True)
                for line in (r2.stdout + r2.stderr).strip().splitlines():
                    print("    " + line)
        else:
            rep.note("`ots` CLI not found — install opentimestamps-client for trustless verification")
    else:
        rep.note("no .ots for the cover block in this bundle "
                 f"(cover_status={manifest['notary'].get('cover_status')}) — re-download later")

    # ── Roughtime time witnesses ───────────────────────────────────────────
    # Reported AFTER Bitcoin and under its own heading, never merged into it:
    # the two answer the same question with different strengths, and collapsing
    # them would quietly lend the weaker one the other's standing.
    print("\nTime witnesses (Roughtime):")
    rt_files = manifest["notary"].get("roughtime_files", {})
    if not rt_files:
        rep.note("no Roughtime witness packets in this bundle — the notary stamps each block "
                 "within a couple of minutes of sealing; re-download later")
    else:
        by_block = {}
        for tag, rel in sorted(rt_files.items()):
            block_str, _, source = tag.partition("-")
            try:
                block = int(block_str)
            except ValueError:
                rep.note(f"skipping malformed roughtime entry {tag!r}")
                continue
            hdr = headers.get(block)
            if not hdr:
                rep.note(f"block #{block} is not in this bundle's chain segment — witness not bound")
                continue
            pinned = RT_PINNED_KEYS.get(source)
            if not pinned:
                # Refusing is the honest outcome: checking a signature against a
                # key shipped in this same bundle would prove nothing.
                rep.note(f'no pinned key for witness "{source}" — its packet was NOT checked '
                         "(a key taken from this bundle proves nothing about this bundle)")
                continue
            label, pubkey, _b64 = pinned
            try:
                with open(os.path.join(root, rel), "rb") as f:
                    packet = f.read()
            except OSError as e:
                rep.note(f"{rel}: unreadable ({e})")
                continue
            try:
                midp, radi = rt_verify(pubkey, bytes.fromhex(hdr["block_hash"]), source, packet)
            except Exception as e:
                rep.bad(f"witness {source} on block #{block}: {e}")
                continue
            by_block.setdefault(block, []).append((label, source, midp, radi))

        tightest = None
        labels = set()
        for block in sorted(by_block):
            for label, source, midp, radi in by_block[block]:
                labels.add(label)
                rep.ok(f"block #{block}: {label} signed this block's hash — existed before "
                       f"{_rt_fmt(midp + radi)} (+/-{radi // 1000} ms)")
                if tightest is None or midp + radi < tightest:
                    tightest = midp + radi

            # Witnesses are queried within a few hundred milliseconds of each
            # other, so their stated intervals MUST overlap. A gap means at least
            # one is wrong about the time. The protocol cannot say which, and
            # neither will this verifier — but silence would be the omission
            # this whole bundle exists to avoid.
            rows = by_block[block]
            if len(rows) >= 2:
                lo = max(m - r for _, _, m, r in rows)
                hi = min(m + r for _, _, m, r in rows)
                if lo > hi:
                    rep.bad(f"block #{block}: the witnesses CONTRADICT each other — their stated "
                            f"times cannot all be true (they miss each other by "
                            f"{(lo - hi) // 1000} ms). At least one is wrong about the time; "
                            "nothing here says which, so this block's bound is not reliable.")

        if tightest is not None:
            print(f"\n    Tightest upper bound across all witnesses: existed before {_rt_fmt(tightest)}")
            print("    This rests on the operators' signing keys, unlike the Bitcoin anchor above.")
            print("    Confirm these keys at their source before relying on the bound:")
            for name in sorted(labels):
                for src, (label, _pk, b64) in RT_PINNED_KEYS.items():
                    if label == name:
                        print(f"      {label:<12} {b64}")
            print(f"      published at {RT_KEY_SOURCE_URL}")

    # ── Extraction (optional) ──────────────────────────────────────────────
    if args.extract:
        if pair_dirs:
            print("\nPer-chunk cipher/plaintext written for independent hash checks:")
            print(f"  {len(pair_dirs)} chunk(s) under extracted/chunks/<seq>-<id>/ "
                  "(plaintext.bin + SHA256SUMS + EXPECTED.txt; ciphertext not duplicated)")
            ex = os.path.relpath(pair_dirs[0], root)
            print("  verify any chunk yourself, e.g.:")
            print(f"    cd {ex} && {sha256sum_check_cmd()}")

        print("\nExtracting media streams from verified payloads:")
        if encrypted and dek is None:
            print("  session is encrypted and no key was supplied — pass --dek or --id-priv")
            print("  to decrypt; payloads are ciphertext, nothing to extract without a key")
        else:
            # For an encrypted session, verified_payloads already hold the
            # decrypted cleartext CBOR (the per-chunk step above replaced the
            # ciphertext once the plaintext hash matched), so extraction is
            # uniform with the cleartext case below.
            outdir = os.path.join(root, "extracted")
            os.makedirs(outdir, exist_ok=True)
            streams = {}
            for seq, cid, payload in sorted(verified_payloads):
                try:
                    decoded = cbor_decode(payload)
                except Exception as e:
                    print(f"  ! chunk seq={seq}: payload CBOR decode failed: {e}")
                    continue
                for s in decoded.get("streams", []):
                    streams.setdefault(s["id"], []).append((seq, s["bytes"]))
            bins = {}  # stream id -> written .bin path
            for sid, parts in streams.items():
                fname = os.path.join(outdir, sid.replace("/", "_") + ".bin")
                with open(fname, "wb") as f:
                    for _, blob in sorted(parts):
                        f.write(blob)
                bins[sid] = fname
                print(f"  wrote {fname} ({len(parts)} fragments)")

            # Remux each camera into a standalone, playable MP4. Dual-camera
            # sessions carry both video.back.* and video.front.*; each becomes
            # its own MP4 with the audio duplicated in (the project's dual-cam
            # export convention: two self-contained files).
            videos = sorted(k for k in bins if k.startswith("video."))
            audios = sorted(k for k in bins if k.startswith("audio."))
            audio_bin = bins[audios[0]] if audios else None
            if videos:
                have_ffmpeg = shutil.which("ffmpeg") is not None
                print("\n  Assembling playable MP4(s):" if have_ffmpeg
                      else "\n  ffmpeg not found — run these to assemble playable MP4(s):")
            for vid in videos:
                # video.back.h264_fmp4.v1 -> "back"; fall back to a sanitized id.
                p = vid.split(".")
                cam = p[1] if len(p) > 1 else vid.replace(".", "_")
                out_mp4 = os.path.join(outdir, f"{cam}.mp4")
                cmd = ["ffmpeg", "-y", "-i", bins[vid]]
                if audio_bin:
                    cmd += ["-i", audio_bin]
                cmd += ["-c", "copy", out_mp4]
                # Copy-pasteable form with paths relative to the bundle root.
                rel = ["ffmpeg", "-i", os.path.relpath(bins[vid], root)]
                if audio_bin:
                    rel += ["-i", os.path.relpath(audio_bin, root)]
                rel += ["-c", "copy", os.path.relpath(out_mp4, root)]
                print("    " + " ".join(rel))
                if shutil.which("ffmpeg"):
                    r = subprocess.run(cmd, capture_output=True, text=True)
                    if r.returncode == 0 and os.path.exists(out_mp4):
                        print(f"      -> wrote {out_mp4}")
                    else:
                        tail = (r.stderr or "").strip().splitlines()[-1:] or ["(no stderr)"]
                        print(f"      ! ffmpeg failed: {tail[0]}")

    # ── What the camera did not capture ────────────────────────────────────
    #
    # Printed for every run, including a clean one: "no frames were held" is
    # itself a finding, and a section that appears only on defects teaches a
    # reader to assume its absence means nothing was checked.
    print("\nFrame continuity (from the signed envelopes):")
    if not frozen_reported:
        # Deliberately not "no freezes": this recording carries no such
        # measurement, and saying it was clean would assert something nobody
        # checked.
        print("  not reported by this recording — it predates this disclosure,")
        print("  so nothing can be said either way about held frames")
    elif not frozen_all:
        print("  every frame was delivered — no held images disclosed")
    else:
        frozen_all.sort(key=lambda f: f[1])
        total = sum(f[2] for f in frozen_all)
        print(f"  {total} frame(s) never reached the recorder, "
              f"over {len(frozen_all)} moment(s):")
        for t_us, frame, missed in frozen_all[:20]:
            ts = datetime.datetime.fromtimestamp(
                t_us / 1e6, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
            print(f"    {ts}Z  frame {frame} held {round(missed * 1000 / 30)} ms "
                  f"({missed} not delivered)")
        if len(frozen_all) > 20:
            print(f"    …and {len(frozen_all) - 20} more")
        print("  The image before each gap was held on screen; the frame that")
        print("  follows it carries an R<n> mark burnt into the overlay, so the")
        print("  picture and this list can be checked against each other.")

    # Front camera (dual-cam only). Printed only when at least one chunk
    # carries the front stream: a single-camera recording has no front footage
    # to disclose anything about, so silence is the honest output — unlike the
    # rear block above, whose absence would hide an unmeasured recording.
    if frozen_front_reported:
        print("\nFrame continuity — front camera (from the same signed envelopes):")
        if not frozen_front_all:
            print("  every front frame was delivered — no held images disclosed")
        else:
            frozen_front_all.sort(key=lambda f: f[0])
            ftotal = sum(f[2] for f in frozen_front_all)
            print(f"  {ftotal} front frame(s) never reached the recorder, "
                  f"over {len(frozen_front_all)} moment(s):")
            for t_us, frame, missed in frozen_front_all[:20]:
                ts = datetime.datetime.fromtimestamp(
                    t_us / 1e6, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
                print(f"    {ts}Z  front frame {frame} held "
                      f"{round(missed * 1000 / 30)} ms ({missed} not delivered)")
            if len(frozen_front_all) > 20:
                print(f"    …and {len(frozen_front_all) - 20} more")

    # ── The clocks the device declared ─────────────────────────────────────
    #
    # Printed on every run, like frame continuity, and for the same reason: a
    # section that only appears on a defect teaches a reader that its absence
    # means everything was fine, when it may mean nobody looked.
    print("\nClocks the device declared (from the signed envelopes):")
    if not time_reported:
        print("  not reported by this recording — it predates this disclosure,")
        print("  so nothing can be said either way about its clocks")
    else:
        def _span(us):
            a = abs(us)
            if a < 1000:
                return f"{a} us"
            if a < 1_000_000:
                return f"{round(a / 1000)} ms"
            if a < 60_000_000:
                return f"{a / 1_000_000:.1f} s"
            if a < 3_600_000_000:
                return f"{round(a / 60_000_000)} min"
            if a < 86_400_000_000:
                return f"{a / 3_600_000_000:.1f} h"
            return f"{a / 86_400_000_000:.1f} days"

        # Past this, the word "agreed" would be a lie. A phone and a time
        # server normally sit within a second or two of each other; a gap of
        # minutes is a finding, not a rounding error, and it must read as one.
        AGREEMENT_LIMIT_US = 5_000_000

        # "satellite time" is only ever declared where it IS satellite time:
        # the phone reports no GPS value on iOS, which exposes no GNSS time to
        # an app — `CLLocation.timestamp` is the device clock stamped at the fix.
        LABEL = {"device": "the phone's own clock", "ntp": "internet time (NTP)",
                 "gps": "satellite time (GPS)", "server": "the Forsheur server"}
        # Worst disagreement per source. `value_us + age_us` is what a source
        # read some time ago is expected to say now, so the remainder is the
        # real divergence. A negative age is a reading taken after `t_us` and
        # subtracts.
        #
        # A source that gives no age is SHOWN BUT NOT SCORED, which reverses
        # what this reader first did. Counting a null age as zero looked like
        # the least favourable, therefore the most honest, reading; it is
        # neither. An undated reading cannot tell a clock eight seconds fast
        # from a fix taken eight seconds ago, and the phone declares no age for
        # GPS on iOS by design — so every stale fix was scored as clock error.
        # One iOS session was condemned at 8.7 s on GPS fixes that refreshed
        # every 6-15 s, while NTP, the one source carrying a real age, put the
        # device clock 23 ms away.
        #
        # `server` is kept OUT of the independent set, and that is a matter of
        # category rather than tuning. The verdict below says "agreed with an
        # independent reference": NTP and GPS are independent of Forsheur, the
        # Forsheur server is not — it reaches the phone in an unsigned header.
        # Counting it cuts both ways: it once condemned a recording whose NTP
        # and GPS agreed to within a second, and it would just as readily
        # "confirm" a clock with nothing independent behind it. Still printed,
        # as a bearing.
        worst, seen, unavailable, server_worst = {}, set(), set(), None
        undated = {}
        for t_us, source, value, unc, age in time_all:
            if source == "device":
                continue
            if value is None:
                unavailable.add(source)
                continue
            d = abs(t_us - (value + (age or 0)))
            if source == "server":
                server_worst = d if server_worst is None else max(server_worst, d)
                continue
            if age is None:
                undated[source] = max(d, undated.get(source, -1))
                continue
            seen.add(source)
            if d > worst.get(source, -1):
                worst[source] = d
        for source in seen:
            undated.pop(source, None)  # dated at least once
        if not seen and not undated:
            print("  the phone had no independent clock to compare against")
        elif not seen:
            print("  an independent clock answered, but the phone never said how old")
            print("  the reading was — nothing can be concluded from it")
        else:
            overall = max(worst.values())
            if overall <= AGREEMENT_LIMIT_US:
                print(f"  agreed with {len(seen)} dated independent reference(s) "
                      f"to within {_span(overall)}")
            else:
                print(f"  DISAGREED with an independent reference by "
                      f"{_span(overall)} — the device clock cannot be taken at "
                      f"face value here")
            for source in sorted(seen):
                print(f"    {LABEL.get(source, source)} — at worst "
                      f"{_span(worst[source])} apart")
        for source in sorted(undated):
            print(f"    {LABEL.get(source, source)} — at worst "
                  f"{_span(undated[source])} apart, but the phone did not say how "
                  f"old the reading was, so the gap may be nothing but a stale "
                  f"reading — not counted above")
        if server_worst is not None:
            print(f"    {LABEL['server']} — at worst {_span(server_worst)} apart "
                  f"(our own clock, sent unsigned — a bearing, not an "
                  f"independent check)")
        for source in sorted(unavailable - seen - set(undated)):
            print(f"    {LABEL.get(source, source)} — unavailable at capture")
        print("  Declared by the device and covered by its signature, so it could")
        print("  not be revised afterwards. This is a cross-check, not a proof of")
        print("  date: that comes from the notary chain and its witnesses above.")

    # ── The on-device screen-refilming check ───────────────────────────────
    print("\nScreen re-filming check (from the signed envelopes):")
    if not fraud_reported:
        # Not "clean": no analysis ran, so there is nothing to report.
        print("  not measured on this recording")
    elif not fraud_all:
        print("  the detector was running, but no segment carries a score")
    else:
        flagged = [v for v in fraud_all if v[2] >= 0.5]
        model = fraud_all[-1][3]
        worst_v = max(fraud_all, key=lambda v: v[2])
        # Only chunks that carry footage can carry a score. The session-open
        # chunk at seq 0 holds no picture at all — just the GPS fix and the
        # session marker — so counting it would report a segment that never
        # existed as one nobody examined.
        media_seqs = {seq for seq, _cid, _payload in verified_payloads if seq >= 1}
        scored_seqs = {v[1] for v in fraud_all}
        unscored = sorted(media_seqs - scored_seqs)
        scored = len(scored_seqs)
        if flagged:
            print(f"  a screen-refilming pattern was flagged in {len(flagged)} "
                  f"of {scored} scored segment(s)")
            for t_us, seq, score, mv, frames in flagged[:20]:
                ts = datetime.datetime.fromtimestamp(
                    t_us / 1e6, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
                print(f"    {ts}Z  segment {seq}: score {score:.3f} "
                      f"over {frames} frame(s), model {mv}")
            if len(flagged) > 20:
                print(f"    …and {len(flagged) - 20} more")
        else:
            print(f"  no screen-refilming pattern detected in {scored} scored segment(s)")
        print(f"  highest score {worst_v[2]:.3f} on a 0-to-1 scale, model {model}")
        if unscored:
            # Naming the expected case is worth the extra branch: "1 segment
            # carries no score" reads like a defect, when the final segment
            # having none is how the mechanism necessarily works.
            if len(unscored) == 1 and unscored[0] == max(media_seqs):
                print("  the last segment carries no score: a segment is analysed")
                print("  after it has already been signed and sent, so its verdict")
                print("  rides in the segment that follows — and the final one has")
                print("  no follower to carry it")
            else:
                listed = ", ".join(str(x) for x in unscored[:10])
                more = "" if len(unscored) <= 10 else f" and {len(unscored) - 10} more"
                print(f"  {len(unscored)} segment(s) carry no score (segment "
                      f"{listed}{more}):")
                print("  a verdict rides in the segment that FOLLOWS the one it")
                print("  describes, so the final segment never has one — and any")
                print("  other gap means an upload was interrupted before its")
                print("  carrier went out")
        print("  A probability from one version of one model, computed on the phone")
        print("  and signed with the segment. It is evidence, not proof, and it says")
        print("  nothing about whether the scene in front of the lens was staged.")

    # ── Verdict ────────────────────────────────────────────────────────────
    # Machine-readable restatement, written BEFORE the verdict is printed so a
    # failure to write it lands above the verdict rather than after it. It
    # carries no judgement the text does not already carry: same counts, same
    # checks, same order.
    if args.json:
        out = {
            "schema": "forsheur-verify-bundle/1",
            "verdict": "pass" if rep.fail == 0 else "fail",
            "failed_checks": rep.fail,
            "notes": rep.warn,
            "chunks_verified": len(verified_payloads),
            "session": {
                "session_id": session.get("session_id"),
                "short_id": session.get("short_id"),
                "encryption": session.get("encryption", "none"),
                "chunk_count": session.get("chunk_count"),
            },
            "checks": rep.events,
            "verifier": {
                "path": os.path.abspath(__file__),
                "sha256": _self_sha256(),
                "version": VERIFIER_VERSION,
            },
        }
        try:
            with open(args.json, "w", encoding="utf-8") as f:
                json.dump(out, f, indent=2, sort_keys=True, ensure_ascii=False)
                f.write("\n")
            print(f"\nMachine-readable summary written to {args.json}")
        except OSError as e:
            # Not a verification failure: every check above still ran. Say so
            # plainly rather than let a disk error read as a crypto verdict.
            print(f"\n! could not write {args.json}: {e}")

    print()
    if rep.fail == 0:
        print(f"VERDICT: PASS — {len(verified_payloads)} chunk(s) fully verified"
              + (f", {rep.warn} note(s)" if rep.warn else ""))
        sys.exit(0)
    print(f"VERDICT: FAIL — {rep.fail} check(s) failed, {rep.warn} note(s)")
    sys.exit(1)


