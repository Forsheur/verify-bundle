#!/usr/bin/env python3
"""Forsheur evidence bundle verifier — Python 3 standard library only.

Verifies, fully offline, that the media in this bundle is exactly what a
genuine device signed and what the Forsheur notary sealed and anchored:

  1. sha256(payload.bin)            == h_received (the hash the device signed)
  2. sha256(envelope.cbor)          -> H_env ; sha256(H_env || H_received)
                                    == the notarized commitment (H_chunk)
  3. device signature over H_chunk, pubkey read from the envelope
     (Ed25519 for chunk format v2, ECDSA P-256 for v3 — the key's width says
     which, and both are implemented here in pure Python)
  4. leaf -> Merkle path -> merkle_root -> block_hash, Ed25519 notary signature
  5. hash-chain segment: every block links prev -> next up to the cover block
  6. the cover block is anchored in Bitcoin (.ots) — three levels:
       a. `ots verify` + your own Bitcoin node  -> fully trustless
       b. built-in .ots parsing                 -> reports the Bitcoin block
          height; cross-check its timestamp on any explorer
       c. neither                               -> seal/signatures still proven

Usage:
    python3 verify_bundle.py <bundle.zip | extracted-directory>
    python3 verify_bundle.py <bundle> --extract    # also write media streams

Nothing here contacts any Forsheur server. The notary public keys ship in the
bundle; you may cross-check them against
https://<the-forsheur-host>/.well-known/forsheur-notary-keys.json

This script arrives inside the archive it checks, which on its own would be
circular: whoever controls the bundle controls the verifier. What breaks the
circle is that the same file is published independently, so the copy you were
given can be compared against a copy nobody handed you:

    shasum -a 256 verify_bundle.py          # or: certutil -hash-file ... SHA256
    https://github.com/Forsheur/verify-bundle   releases, with SHA256SUMS
    https://<the-forsheur-host>/custody.sha256

A mismatch does not by itself mean the bundle is bad -- servers are upgraded
and older bundles keep the verifier they shipped with, so check the version
below against the CHANGELOG first. It does mean you should verify with a copy
you obtained yourself before believing anything this one printed.
"""

