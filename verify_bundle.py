def frozen_frames_from_envelope(envelope, stream_id="video.frozen.v1"):
    """Freezes the recording device disclosed, re-derived from the SIGNED
    envelope — not from anything the server said.

    When the camera sensor skips, the previous image simply stays on screen
    longer: no frame is duplicated in the file, only its declared duration
    grows. Without this list a reader cannot tell a held image from a still
    scene, so the device records each one inside the envelope it signs, and
    this verifier reads it back from those same bytes.

    Returns None when the envelope carries NO such stream — a recording that
    predates this disclosure, about which nothing may be claimed — and a list
    (possibly empty) when it does. That difference is the whole point: an empty
    stream says "measured, nothing found", no stream says nobody looked, and
    collapsing them would report footage no code ever examined as flawless.

    A malformed stream degrades to an empty list rather than an error: failing
    to parse a disclosure must never sink the verification of everything else.
    """
    try:
        env = cbor_decode(envelope)
    except Exception:
        return None
    out = []
    present = False
    for st in (env.get("streams_envelope") or []):
        if not isinstance(st, dict) or st.get("id") != stream_id:
            continue
        present = True
        for s in (st.get("samples") or []):
            if isinstance(s, list) and len(s) >= 3 and all(isinstance(v, int) for v in s[:3]):
                out.append((s[0], s[1], s[2]))
    return out if present else None


def time_refs_from_envelope(envelope):
    """The clocks the device declared, re-derived from the SIGNED envelope.

    The phone consults up to four references at capture — its own clock, an
    internet time server, the satellite fix, and our server's clock as it last
    saw it — and states all four on every chunk, with a null value where a
    source was unavailable.

    NONE OF THIS PROVES A DATE. Every figure is the device's own claim, and a
    hostile device can claim anything. What the signature buys is that it
    cannot change its story afterwards, and that disagreement between sources
    becomes visible instead of staying hidden. The bound on time comes from the
    notary chain and its outside witnesses, checked further up this report.

    Returns None when no such stream exists (a recording predating the
    disclosure), else a list of tuples (t_us, source, value_us, uncertainty_us,
    age_us) where any of the last three may be None. `age_us` is SIGNED: the
    envelope is built when the chunk closes, so a reading taken during the
    chunk is newer than `t_us` and carries a negative age. A null age means
    the phone could not date the reading at all.
    """
    try:
        env = cbor_decode(envelope)
    except Exception:
        return None
    out = []
    present = False
    for st in (env.get("streams_envelope") or []):
        if not isinstance(st, dict) or st.get("id") != "time.v1":
            continue
        present = True
        for sm in (st.get("samples") or []):
            if not isinstance(sm, list) or len(sm) < 5:
                continue
            t_us, source, value, unc, age = sm[0], sm[1], sm[2], sm[3], sm[4]
            if not isinstance(t_us, int) or not isinstance(source, str):
                continue
            num = lambda v: v if isinstance(v, int) else None
            out.append((t_us, source, num(value), num(unc), num(age)))
    return out if present else None


def fraud_verdicts_from_envelope(envelope):
    """On-device screen-refilming verdicts, re-derived from the SIGNED envelope.

    Each verdict names the `seq` it is ABOUT, which is an earlier chunk than
    the one carrying it: the network finishes scoring a segment after that
    segment has already been built and sent.

    A score is a probability produced by one version of one model. It is
    evidence, not proof, and it says nothing about whether the scene itself was
    staged — which is why it is reported in its own section here and never
    folded into the checks above.

    Returns None when the stream is absent, meaning no analysis ran at all —
    never "it looked clean". An empty list means the detector was running but
    declared nothing in that chunk.
    """
    try:
        env = cbor_decode(envelope)
    except Exception:
        return None
    out = []
    present = False
    for st in (env.get("streams_envelope") or []):
        if not isinstance(st, dict) or st.get("id") != "video.fraud.v1":
            continue
        present = True
        for sm in (st.get("samples") or []):
            if (isinstance(sm, list) and len(sm) >= 5
                    and isinstance(sm[0], int) and isinstance(sm[1], int)
                    and isinstance(sm[2], (int, float)) and isinstance(sm[3], str)
                    and isinstance(sm[4], int)):
                out.append((sm[0], sm[1], float(sm[2]), sm[3], sm[4]))
    return out if present else None


def cbor_decode(data):
    def rd(i):
        ib = data[i]
        major, info = ib >> 5, ib & 31
        i += 1
        if info < 24:
            n = info
        elif info == 24:
            n = data[i]
            i += 1
        elif info == 25:
            n = int.from_bytes(data[i:i + 2], "big")
            i += 2
        elif info == 26:
            n = int.from_bytes(data[i:i + 4], "big")
            i += 4
        elif info == 27:
            n = int.from_bytes(data[i:i + 8], "big")
            i += 8
        else:
            raise ValueError("indefinite length unsupported")
        if major == 0:
            return n, i
        if major == 1:
            return -1 - n, i
        if major == 2:
            return bytes(data[i:i + n]), i + n
        if major == 3:
            return bytes(data[i:i + n]).decode("utf-8"), i + n
        if major == 4:
            arr = []
            for _ in range(n):
                v, i = rd(i)
                arr.append(v)
            return arr, i
        if major == 5:
            m = {}
            for _ in range(n):
                k, i = rd(i)
                v, i = rd(i)
                m[k] = v
            return m, i
        if major == 7:
            if info == 22:
                return None, i
            if info == 20:
                return False, i
            if info == 21:
                return True, i
            # Floats. `n` already holds the raw bits, read above. Without these
            # any envelope carrying a GPS fix — every outdoor recording — was
            # undecodable here, and every disclosure lifted from it silently
            # read as "not reported". Our encoder only ever emits the 64-bit
            # form; the two shorter ones are accepted because the format allows
            # them and refusing them would be a difference from the spec that
            # nobody could see until it bit.
            if info == 25:
                return struct.unpack(">e", n.to_bytes(2, "big"))[0], i
            if info == 26:
                return struct.unpack(">f", n.to_bytes(4, "big"))[0], i
            if info == 27:
                return struct.unpack(">d", n.to_bytes(8, "big"))[0], i
        raise ValueError("unsupported CBOR item")

    v, _ = rd(0)
    return v


# ---------------------------------------------------------------------------
# Minimal .ots reader — extracts the committed digest + Bitcoin block heights
# ---------------------------------------------------------------------------

_OTS_MAGIC = b"\x00OpenTimestamps\x00\x00Proof\x00\xbf\x89\xe2\xe8\x84\xe8\x92\x94\x01"
_BITCOIN_TAG = bytes.fromhex("0588960d73d71901")


def ots_info(data):
    """Parse AND EXECUTE the .ots operation tree.

    Returns (initial_digest, [(bitcoin_height, computed_digest_at_attestation)])
    or None on parse failure. The digest reached at a Bitcoin attestation IS,
    by OTS semantics, the raw merkle-root bytes of the Bitcoin block at that
    height — so the caller can hand the user one exact 32-byte value to compare
    against the block header, no full blockchain needed.
    """
    try:
        if not data.startswith(_OTS_MAGIC):
            return None
        pos = [len(_OTS_MAGIC)]

        def varint():
            r, shift = 0, 0
            while True:
                b = data[pos[0]]
                pos[0] += 1
                r |= (b & 0x7F) << shift
                if not b & 0x80:
                    return r
                shift += 7

        # NB: the trailing \x01 of _OTS_MAGIC is already the version varint —
        # the next byte is the digest type directly.
        dt = data[pos[0]]
        pos[0] += 1
        dlen = {0x02: 20, 0x03: 20, 0x08: 32}.get(dt)
        if dlen is None:
            return None
        initial = bytes(data[pos[0]:pos[0] + dlen])
        pos[0] += dlen
        results = []

        def parse_ts(digest):
            while True:
                tag = data[pos[0]]
                pos[0] += 1
                if tag == 0xFF:
                    # Fork: one branch parsed recursively from the CURRENT
                    # digest, then continue this branch with the same digest.
                    parse_ts(digest)
                    continue
                if tag == 0x00:
                    atag = bytes(data[pos[0]:pos[0] + 8])
                    pos[0] += 8
                    plen = varint()
                    payload = bytes(data[pos[0]:pos[0] + plen])
                    pos[0] += plen
                    if atag == _BITCOIN_TAG:
                        h, shift = 0, 0
                        for b in payload:
                            h |= (b & 0x7F) << shift
                            if not b & 0x80:
                                break
                            shift += 7
                        results.append((h, digest))
                    return
                # Execute the op on the running digest.
                if tag == 0xF0:  # append
                    n = varint()
                    digest = digest + bytes(data[pos[0]:pos[0] + n])
                    pos[0] += n
                elif tag == 0xF1:  # prepend
                    n = varint()
                    digest = bytes(data[pos[0]:pos[0] + n]) + digest
                    pos[0] += n
                elif tag == 0x08:
                    digest = hashlib.sha256(digest).digest()
                elif tag == 0x02:
                    digest = hashlib.sha1(digest).digest()
                elif tag == 0x03:
                    try:
                        digest = hashlib.new("ripemd160", digest).digest()
                    except (ValueError, TypeError):
                        # RIPEMD160 lives in OpenSSL's legacy provider, which is
                        # disabled by default on many modern Linux distros
                        # (OpenSSL 3.0: Ubuntu 22.04+, Debian 12, RHEL 9). Degrade
                        # this branch to unverifiable instead of crashing the run.
                        digest = None
                elif tag == 0xF2:  # reverse
                    digest = digest[::-1]
                elif tag == 0xF3:  # hexlify
                    digest = digest.hex().encode()
                elif tag == 0x67:  # keccak256 — not in stdlib; branch unverifiable
                    digest = None
                else:
                    raise ValueError("unknown op 0x%02x" % tag)
                if digest is None:
                    return

        parse_ts(initial)
        return initial, results
    except Exception:
        return None


