# Ed25519 verification (RFC 8032), pure Python. Slow but we check few sigs.
# ---------------------------------------------------------------------------

_P = 2**255 - 19
_L = 2**252 + 27742317777372353535851937790883648493
_D = (-121665 * pow(121666, _P - 2, _P)) % _P
_I = pow(2, (_P - 1) // 4, _P)


def _xrecover(y):
    xx = (y * y - 1) * pow(_D * y * y + 1, _P - 2, _P)
    x = pow(xx, (_P + 3) // 8, _P)
    if (x * x - xx) % _P != 0:
        x = (x * _I) % _P
    if (x * x - xx) % _P != 0:
        return None
    if x % 2 != 0:
        x = _P - x
    return x


_BY = (4 * pow(5, _P - 2, _P)) % _P
_BX = _xrecover(_BY)
_BASE = (_BX, _BY, 1, (_BX * _BY) % _P)


def _pt_add(p, q):
    x1, y1, z1, t1 = p
    x2, y2, z2, t2 = q
    a = (y1 - x1) * (y2 - x2) % _P
    b = (y1 + x1) * (y2 + x2) % _P
    c = t1 * 2 * _D * t2 % _P
    dd = z1 * 2 * z2 % _P
    e, f, g, h = b - a, dd - c, dd + c, b + a
    return (e * f % _P, g * h % _P, f * g % _P, e * h % _P)


def _pt_mul(p, e):
    q = (0, 1, 1, 0)
    while e > 0:
        if e & 1:
            q = _pt_add(q, p)
        p = _pt_add(p, p)
        e >>= 1
    return q


def _pt_decompress(s):
    if len(s) != 32:
        return None
    y = int.from_bytes(s, "little") & ((1 << 255) - 1)
    if y >= _P:
        return None
    sign = s[31] >> 7
    x = _xrecover(y)
    if x is None:
        return None
    if x & 1 != sign:
        x = _P - x
    if (-x * x + y * y - 1 - _D * x * x * y * y) % _P != 0:
        return None
    return (x, y, 1, (x * y) % _P)


def _pt_compress(p):
    x, y, z, _ = p
    zi = pow(z, _P - 2, _P)
    x, y = x * zi % _P, y * zi % _P
    return (y | ((x & 1) << 255)).to_bytes(32, "little")


def ed25519_verify(pub: bytes, sig: bytes, msg: bytes) -> bool:
    if len(pub) != 32 or len(sig) != 64:
        return False
    a = _pt_decompress(pub)
    r = _pt_decompress(sig[:32])
    if a is None or r is None:
        return False
    s = int.from_bytes(sig[32:], "little")
    if s >= _L:
        return False
    h = int.from_bytes(hashlib.sha512(sig[:32] + pub + msg).digest(), "little") % _L
    return _pt_compress(_pt_mul(_BASE, s)) == _pt_compress(_pt_add(r, _pt_mul(a, h)))


# ---------------------------------------------------------------------------
# Canonical CBOR (positional arrays, mirror of notary/src/canonical.rs)
# ---------------------------------------------------------------------------

def _cbor_head(major, n):
    if n < 24:
        return bytes([(major << 5) | n])
    if n < 0x100:
        return bytes([(major << 5) | 24, n])
    if n < 0x10000:
        return bytes([(major << 5) | 25]) + n.to_bytes(2, "big")
    if n < 0x100000000:
        return bytes([(major << 5) | 26]) + n.to_bytes(4, "big")
    return bytes([(major << 5) | 27]) + n.to_bytes(8, "big")


def _cbor_uint(n):
    return _cbor_head(0, n)


def _cbor_bytes(b):
    return _cbor_head(2, len(b)) + b


def _cbor_text(s):
    e = s.encode("utf-8")
    return _cbor_head(3, len(e)) + e


def leaf_hash(entry_type, ref_id, received_at, commitment, plaintext):
    data = _cbor_head(4, 6) + _cbor_uint(1) + _cbor_text(entry_type) + _cbor_text(ref_id)
    data += _cbor_uint(received_at) + _cbor_bytes(commitment)
    data += _cbor_bytes(plaintext) if plaintext is not None else b"\xf6"
    return hashlib.sha256(b"\x00" + data).digest()


def block_hash_of(index, prev, root, seal_time):
    data = _cbor_head(4, 5) + _cbor_uint(1) + _cbor_uint(index)
    data += _cbor_bytes(prev) + _cbor_bytes(root) + _cbor_uint(seal_time)
    return hashlib.sha256(b"\x02" + data).digest()


# ---------------------------------------------------------------------------
# RFC 6962 Merkle audit path (mirror of notary/src/merkle.rs)
# ---------------------------------------------------------------------------

def _node(l, r):
    return hashlib.sha256(b"\x01" + l + r).digest()


def _split(n):
    k = 1
    while (k << 1) < n:
        k <<= 1
    return k


def root_from_path(leaf, index, size, path):
    if size == 1:
        if path:
            raise ValueError("audit path too long")
        return leaf
    k = _split(size)
    rest, top = path[:-1], path[-1]
    if index < k:
        return _node(root_from_path(leaf, index, k, rest), top)
    return _node(top, root_from_path(leaf, index - k, size - k, rest))


# ---------------------------------------------------------------------------
# ECDSA P-256 verification (FIPS 186-4 / SEC 1), pure Python.
# ---------------------------------------------------------------------------
#
# The device signature moved from Ed25519 to P-256 with chunk format v3, when
# the signing key moved into the phone's secure element. Both curves live here
# permanently: v2 recordings keep verifying under Ed25519 above, the notary's
# own block signatures are Ed25519, and so is Roughtime. Nothing was replaced.
#
# Written out longhand rather than pulled from a library on purpose. The claim
# this file exists to support is that a stranger can check a Forsheur recording
# with nothing but a Python interpreter — no pip, no network, no trust in us.
# That claim is worth more than the ~90 lines below.
#
# VERIFICATION ONLY. There is no signing here, and that is a deliberate
# asymmetry: verification handles no secret, so a slow or non-constant-time
# implementation leaks nothing. Signing would need a nonce, and a nonce that
# repeats hands over the private key outright — never something to hand-roll.

_P256_P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
_P256_N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
_P256_B = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B
_P256_GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
_P256_GY = 0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5
# The curve is y² = x³ - 3x + b: `a` is -3 for every NIST prime curve, which is
# what makes the doubling formula below shorter than the general one.


def _p256_dbl(pt):
    """Point doubling in Jacobian coordinates (x = X/Z², y = Y/Z³).

    Jacobian rather than affine for one reason: affine addition needs a modular
    inverse per step, and a 256-bit scalar multiplication takes some 380 of
    them. Deferring to a single inverse at the end (see `_p256_affine_x`) turns
    a verification that took seconds into one that takes tens of milliseconds —
    on a file whose whole point is that someone will actually run it.

    Formula `dbl-2001-b` for a = -3, from the Explicit-Formulas Database.
    """
    x, y, z = pt
    if z == 0 or y == 0:
        return (0, 0, 0)  # point at infinity
    p = _P256_P
    delta = (z * z) % p
    gamma = (y * y) % p
    beta = (x * gamma) % p
    alpha = (3 * (x - delta) * (x + delta)) % p
    x3 = (alpha * alpha - 8 * beta) % p
    z3 = ((y + z) * (y + z) - gamma - delta) % p
    y3 = (alpha * (4 * beta - x3) - 8 * gamma * gamma) % p
    return (x3, y3, z3)


def _p256_add(pt1, pt2):
    """Point addition in Jacobian coordinates (`add-2007-bl`)."""
    x1, y1, z1 = pt1
    x2, y2, z2 = pt2
    if z1 == 0:
        return pt2
    if z2 == 0:
        return pt1
    p = _P256_P
    z1z1 = (z1 * z1) % p
    z2z2 = (z2 * z2) % p
    u1 = (x1 * z2z2) % p
    u2 = (x2 * z1z1) % p
    s1 = (y1 * z2 * z2z2) % p
    s2 = (y2 * z1 * z1z1) % p
    if u1 == u2:
        # Same x. Either the same point (double it) or P and -P (infinity).
        return _p256_dbl(pt1) if s1 == s2 else (0, 0, 0)
    h = (u2 - u1) % p
    i = (2 * h) % p
    i = (i * i) % p
    j = (h * i) % p
    r = (2 * (s2 - s1)) % p
    v = (u1 * i) % p
    x3 = (r * r - j - 2 * v) % p
    y3 = (r * (v - x3) - 2 * s1 * j) % p
    z3 = (((z1 + z2) * (z1 + z2) - z1z1 - z2z2) * h) % p
    return (x3, y3, z3)


def _p256_mul(pt, k):
    """Scalar multiplication, plain double-and-add.

    Not constant time, and it does not need to be: `k` here is derived from the
    signature and the message, both public. No secret passes through this file.
    """
    result = (0, 0, 0)
    addend = pt
    while k:
        if k & 1:
            result = _p256_add(result, addend)
        addend = _p256_dbl(addend)
        k >>= 1
    return result


def _p256_affine_x(pt):
    """The affine x of a Jacobian point, or None at infinity.

    The single modular inversion of the whole verification.
    """
    x, _y, z = pt
    if z == 0:
        return None
    p = _P256_P
    zinv = pow(z, p - 2, p)  # Fermat: z^(p-2) ≡ z⁻¹ for prime p
    return (x * zinv * zinv) % p


def p256_verify(pub: bytes, sig: bytes, msg: bytes) -> bool:
    """ECDSA P-256 over SHA-256, raw r‖s signature, uncompressed SEC1 key.

    `msg` is H_chunk and is signed AS A MESSAGE — this function hashes it. See
    `forsheur-chunk/FORMAT_V3_SIGNING.md` §3.5 for why the format chose that
    over signing the digest directly: a prehashed variant would have needed
    DIGEST_NONE keys, which StrongBox is not obliged to allow, so it would have
    failed first on the best-protected phones.

    Returns False rather than raising for every malformed input, so one bad
    chunk in a bundle reports as one bad chunk rather than aborting the run.
    """
    # Uncompressed SEC1 only: 0x04 || X || Y. A compressed key (33 bytes) is
    # refused rather than decompressed — recovering y needs a modular square
    # root, and this file does not carry a primitive it does not need.
    if len(pub) != 65 or pub[0] != 0x04:
        return False
    # Raw r‖s only. A DER signature is 70-72 bytes and variable; accepting both
    # encodings would mean two representations of one signature, therefore two
    # chunk ids for one chunk.
    if len(sig) != 64:
        return False

    p, n = _P256_P, _P256_N
    qx = int.from_bytes(pub[1:33], "big")
    qy = int.from_bytes(pub[33:65], "big")
    if qx >= p or qy >= p:
        return False
    # The key must actually be ON the curve. Skipping this is how invalid-curve
    # attacks start: a point from another, weaker curve would still run through
    # the arithmetic below and produce an answer.
    if (qy * qy - (qx * qx * qx - 3 * qx + _P256_B)) % p != 0:
        return False

    r = int.from_bytes(sig[:32], "big")
    s = int.from_bytes(sig[32:], "big")
    if not (1 <= r < n and 1 <= s < n):
        return False

    # FIPS 186-4 §6.4: e is the leftmost min(N, outlen) bits of the hash. Here
    # both are 256, so the digest is used whole — no truncation, no shift.
    e = int.from_bytes(hashlib.sha256(msg).digest(), "big")

    w = pow(s, n - 2, n)
    u1 = (e * w) % n
    u2 = (r * w) % n
    point = _p256_add(
        _p256_mul((_P256_GX, _P256_GY, 1), u1),
        _p256_mul((qx, qy, 1), u2),
    )
    x = _p256_affine_x(point)
    if x is None:
        return False
    return (x % n) == r


def device_sig_verify(pub: bytes, sig: bytes, msg: bytes) -> bool:
    """The device signature, under whichever curve the key's WIDTH names.

    32 bytes ⇒ Ed25519 (chunk format v2), 65 ⇒ P-256 (v3). The single place
    this file decides; a second one could decide differently, and the day they
    disagreed one of them would stop checking something.

    The key itself is not taken on trust here — the caller has already required
    it to appear verbatim inside the envelope that the signature covers.
    """
    if len(pub) == 32:
        return ed25519_verify(pub, sig, msg)
    if len(pub) == 65:
        return p256_verify(pub, sig, msg)
    return False


