def _self_sha256():
    """SHA-256 of this script, so a report quoting it can name which copy ran.

    Bundles are regenerated on every request and this file is compiled into the
    server, so two archives of the same session can legitimately carry two
    different verifiers. A reader comparing two reports is entitled to see
    which one produced which."""
    try:
        with open(os.path.abspath(__file__), "rb") as f:
            return hashlib.sha256(f.read()).hexdigest()
    except OSError:
        return None


class Report:
    """Counts the checks and, incidentally, records them.

    `events` exists so `--json` can emit the same checks the human text shows,
    from the same call sites, in the same order. It is fed here rather than at
    each caller on purpose: a second list assembled separately would be a
    second account of what happened, free to disagree with the first."""

    def __init__(self):
        self.fail = 0
        self.warn = 0
        self.events = []

    def ok(self, msg):
        self.events.append({"status": "ok", "message": msg})
        print("  ✓ " + msg)

    def bad(self, msg):
        self.fail += 1
        self.events.append({"status": "fail", "message": msg})
        print("  ✗ FAIL: " + msg)

    def note(self, msg):
        self.warn += 1
        self.events.append({"status": "note", "message": msg})
        print("  ! " + msg)


