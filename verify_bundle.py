RT_SREP_CONTEXT = b"RoughTime v1 response signature\x00"


def _rt_tag(name):
    """4-byte tag read as a little-endian uint32, as the wire encodes it."""
    return int.from_bytes(name.encode().ljust(4, b"\x00"), "little")


def rt_parse(buf):
    """Parse [N][offsets x (N-1)][tags x N][values] into {tag: bytes}.

    Validates the header, the 4-aligned monotonic offsets and every bound.
    Raises on anything malformed rather than returning a partial message a
    later check might accept.
    """
    if len(buf) < 4:
        raise ValueError("message shorter than its header")
    n = int.from_bytes(buf[0:4], "little")
    if n == 0 or n > 1024:
        raise ValueError("implausible tag count %d" % n)
    header_len = 4 + 4 * (n - 1) + 4 * n
    if len(buf) < header_len:
        raise ValueError("truncated header")
    offsets = [int.from_bytes(buf[4 + 4 * i:8 + 4 * i], "little") for i in range(n - 1)]
    base = 4 + 4 * (n - 1)
    tags = [int.from_bytes(buf[base + 4 * i:base + 4 * i + 4], "little") for i in range(n)]
    values = buf[header_len:]
    out, prev = {}, 0
    for k, tag in enumerate(tags):
        end = len(values) if k == n - 1 else offsets[k]
        if end % 4 != 0 or end < prev or end > len(values):
            raise ValueError("bad offset for tag %d" % k)
        out[tag] = values[prev:end]
        prev = end
    return out


def _rt_get(msg, name):
    v = msg.get(_rt_tag(name))
    if v is None:
        raise ValueError("missing " + name)
    return v


def rt_nonce(block_hash: bytes, source: str) -> bytes:
    """The nonce the notary derived for this (block, witness) pair.

    Deterministic and recomputable from the PUBLIC block hash, which is what
    lets anyone confirm the witness signed a tree containing THIS block rather
    than some value Forsheur chose. Mirrors nonce_for() in roughtime.rs.
    """
    return hashlib.sha512(b"forsheur-roughtime-nonce-v1" + block_hash + source.encode()).digest()


def _rt_merkle_root(nonce: bytes, indx: bytes, path: bytes) -> bytes:
    if len(path) % 64 != 0:
        raise ValueError("PATH length is not a multiple of 64")
    index = int.from_bytes(indx[:4], "little")
    node = hashlib.sha512(b"\x00" + nonce).digest()
    for o in range(0, len(path), 64):
        sibling = path[o:o + 64]
        if index & 1 == 0:
            node = hashlib.sha512(b"\x01" + node + sibling).digest()
        else:
            node = hashlib.sha512(b"\x01" + sibling + node).digest()
        index >>= 1
    return node


def rt_verify(pubkey: bytes, block_hash: bytes, source: str, packet: bytes):
    """Verify one witness packet. Returns (midpoint_us, radius_us); raises on failure.

    Four checks, in order:
      1. the pinned long-term key signs the delegation cert (DELE)
      2. the delegated key (DELE.PUBK) signs the response body (SREP)
      3. our nonce's leaf hashes up PATH/INDX to the signed SREP.ROOT
      4. MIDP falls inside the delegation's validity window [MINT, MAXT]
    """
    top = rt_parse(packet)
    sig = _rt_get(top, "SIG")
    srep = _rt_get(top, "SREP")
    cert = _rt_get(top, "CERT")
    indx = _rt_get(top, "INDX")
    path = _rt_get(top, "PATH")

    cert_msg = rt_parse(cert)
    dele = _rt_get(cert_msg, "DELE")
    if not ed25519_verify(pubkey, _rt_get(cert_msg, "SIG"), RT_DELE_CONTEXT + dele):
        raise ValueError("delegation certificate is not signed by the pinned long-term key")

    dele_msg = rt_parse(dele)
    pubk = _rt_get(dele_msg, "PUBK")
    mint = int.from_bytes(_rt_get(dele_msg, "MINT")[:8], "little")
    maxt = int.from_bytes(_rt_get(dele_msg, "MAXT")[:8], "little")

    if not ed25519_verify(pubk, sig, RT_SREP_CONTEXT + srep):
        raise ValueError("response body is not signed by the delegated key")

    srep_msg = rt_parse(srep)
    root = _rt_get(srep_msg, "ROOT")
    midp = int.from_bytes(_rt_get(srep_msg, "MIDP")[:8], "little")
    radi = int.from_bytes(_rt_get(srep_msg, "RADI")[:4], "little")
    if len(root) != 64:
        raise ValueError("ROOT is %d bytes, expected 64" % len(root))

    if _rt_merkle_root(rt_nonce(block_hash, source), indx, path) != root:
        raise ValueError("this block's nonce is not in the signed tree")
    if not (mint <= midp <= maxt):
        raise ValueError("the signed time falls outside the delegation's validity window")
    return midp, radi


def _rt_fmt(us):
    return datetime.datetime.fromtimestamp(us / 1e6, datetime.timezone.utc).isoformat()


# ---------------------------------------------------------------------------
# Optional decryption of an encrypted session.
#
# The provenance verification above is pure standard library. Decryption is an
# OPT-IN extra for a recipient who legitimately holds a key, so it may pull in
# packages the base verification never needs:
#   * `cryptography` — AES-256-GCM (not in the stdlib)
#   * `pynacl`       — crypto_box_seal_open, for the --id-priv path
#   * `mnemonic`     — only if --id-priv is given as BIP39 words instead of hex
#
# Nothing here weakens the promise: the server never holds the DEK, the bundle
# ships only ciphertext, and the key comes from the user out-of-band. After
# decryption we re-check sha256(plaintext) against the device-signed plaintext
# hash, so a wrong key (or a decoy envelope) fails loudly instead of producing
# plausible garbage.
# ---------------------------------------------------------------------------

def _parse_id_priv(text):
    """A 32-byte X25519 identity private key, as 64 hex chars or BIP39 words."""
    raw = text.strip()
    compact = raw.replace(" ", "")
    if len(compact) == 64:
        try:
            return bytes.fromhex(compact)
        except ValueError:
            pass
    words = raw.split()
    if len(words) in (12, 15, 18, 21, 24):
        try:
            from mnemonic import Mnemonic
        except ImportError:
            sys.exit("--id-priv looks like a BIP39 mnemonic; decode it with "
                     "`pip install mnemonic`, or pass the 64-hex-character form")
        try:
            return bytes(Mnemonic("english").to_entropy(words))
        except Exception as e:  # noqa: BLE001 — surface any wordlist/checksum error
            sys.exit(f"invalid BIP39 mnemonic: {e}")
    sys.exit("--id-priv must be 64 hex characters or a BIP39 mnemonic (e.g. 24 words)")


def _dek_from_id_priv(root, manifest, id_priv):
    enc = manifest.get("encryption_keys")
    if not enc:
        sys.exit("this bundle has no encryption_keys section — nothing is sealed to open")
    try:
        from nacl.public import PrivateKey, SealedBox
        from nacl.exceptions import CryptoError as NaclError
    except ImportError:
        sys.exit("--id-priv needs PyNaCl: pip install pynacl")
    with open(os.path.join(root, enc["envelopes"]), "rb") as f:
        sealed_list = json.load(f).get("sealed_deks", [])
    box = SealedBox(PrivateKey(id_priv))
    for hexblob in sealed_list:
        try:
            dek = bytes(box.decrypt(bytes.fromhex(hexblob)))
        except (NaclError, ValueError):
            continue  # a real envelope sealed to someone else, or a decoy
        if len(dek) == 32:
            return dek
    sys.exit(f"none of the {len(sealed_list)} sealed envelopes open with this id_priv — "
             "was this identity granted access when the session was recorded?")


def _prompt_secret(label):
    """Read a secret from the console WITHOUT echoing it, so it never lands in
    shell history, the process table, or the terminal scrollback. getpass hides
    input on both Unix (termios) and Windows (msvcrt)."""
    try:
        s = getpass.getpass("%s (input hidden — not echoed): " % label).strip()
    except (EOFError, KeyboardInterrupt):
        sys.exit("\naborted")
    if not s:
        sys.exit("no input provided")
    return s


def resolve_dek(root, manifest, args):
    """Return a 32-byte DEK from --dek or --id-priv, or None if neither given.

    Secrets are NEVER accepted on the command line (that would leak them into
    shell history and `ps`): --dek and --id-priv prompt interactively with hidden
    input. --id-priv-file is the non-interactive escape hatch (a file is not
    shell history) for automation."""
    if args.dek:
        hexs = _prompt_secret("Paste the 32-byte session DEK (hex)")
        try:
            dek = bytes.fromhex(hexs)
        except ValueError:
            sys.exit("DEK must be 64 hex characters (32 bytes)")
        if len(dek) != 32:
            sys.exit("DEK must decode to exactly 32 bytes")
        return dek
    if args.id_priv_file:
        with open(args.id_priv_file) as f:
            return _dek_from_id_priv(root, manifest, _parse_id_priv(f.read()))
    if args.id_priv:
        key = _prompt_secret("Paste your identity private key (64 hex, or 24 BIP39 words)")
        return _dek_from_id_priv(root, manifest, _parse_id_priv(key))
    return None


def aesgcm_decrypt(dek, iv_hex, ciphertext_and_tag):
    """AES-256-GCM: payload.bin is ciphertext with the 16-byte tag appended."""
    try:
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    except ImportError:
        sys.exit("decryption needs the `cryptography` package: pip install cryptography")
    return AESGCM(dek).decrypt(bytes.fromhex(iv_hex), ciphertext_and_tag, None)


def sha256sum_check_cmd():
    """The right `... -c SHA256SUMS` invocation for this OS (Linux ships
    `sha256sum`; macOS ships `shasum`)."""
    if shutil.which("sha256sum"):
        return "sha256sum -c SHA256SUMS"
    if shutil.which("shasum"):
        return "shasum -a 256 -c SHA256SUMS"
    return "sha256sum -c SHA256SUMS"  # Linux default (Windows: use verify_bundle.ps1)


def write_decrypted_pair(root, seq, cid, plaintext, h_received, plaintext_hash, payload_rel):
    """Write ONLY the decrypted bytes of one chunk. The ciphertext already lives
    in the bundle at `payload_rel`, so we never copy it — the SHA256SUMS checkfile
    references it in place (relative path), yet still lets `sha256sum -c` verify
    BOTH the plaintext and the ciphertext at once, no trust in this script needed."""
    d = os.path.join(root, "extracted", "chunks", "%04d-%s" % (seq, cid))
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "plaintext.bin"), "wb") as f:
        f.write(plaintext)
    ct_rel = os.path.relpath(os.path.join(root, payload_rel), d)  # bundle ciphertext, not copied
    if h_received and plaintext_hash:
        with open(os.path.join(d, "SHA256SUMS"), "w") as f:
            f.write("%s  plaintext.bin\n%s  %s\n" % (plaintext_hash, h_received, ct_rel))
    with open(os.path.join(d, "EXPECTED.txt"), "w") as f:
        f.write(
            "Independent hash check (no trust in verify_bundle.py needed):\n"
            "    sha256sum -c SHA256SUMS        (macOS: shasum -a 256 -c SHA256SUMS)\n"
            "  Checks plaintext.bin (here) AND the bundle's original ciphertext in place\n"
            "  (%s) — the ciphertext is NOT duplicated.\n\n"
            "plaintext.bin  expected sha256 = %s\n"
            "    the pre-encryption plaintext hash the PHONE signed.\n"
            "ciphertext (%s)  expected sha256 = %s\n"
            "    h_received: the ENCRYPTED bytes the device signed and the notary sealed.\n"
            % (payload_rel, plaintext_hash or "(unavailable)",
               payload_rel, h_received or "(unavailable)")
        )
    return d


